def _слить(события, темы) -> tuple:
    """События компании, затем темы рынка (Brain/news_types.py — тот же список, что у отбора новостей без компании).
    Тип с тем же именем в обоих списках (санкции, облигации) — один тип: хэштеги и слова складываются. Раньше тема
    «облигации» с ОФЗ и доходностями молча выпадала, оставалось только «облигаци»."""
    итог = [[тип, list(теги), rx] for тип, теги, rx in события]
    по_имени = {т[0]: т for т in итог}
    for тип, теги, rx, _где in темы:
        if тип in по_имени:
            т = по_имени[тип]
            т[1] += [x for x in теги if x not in т[1]]
            т[2] = f"{т[2]}|{rx}"
        else:
            итог.append([тип, list(теги), rx])
    return tuple((тип, теги, rx) for тип, теги, rx in итог)


