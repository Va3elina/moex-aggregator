def ключ_тега(тип: str) -> str:
    """Ключ узла-тега: tag:тип/нефть_газ_и_топливо — без пробелов и запятых (id узла идёт в адрес ручки)."""
    return тип.replace(",", "").replace(" ", "_")


def sql_ключ_тега(expr: str) -> str:
    """То же в SQL — одинаково с ключ_тега()."""
    return f"replace(replace({expr}, ',', ''), ' ', '_')"


def норм_тег(t: str) -> str:
    return t.lower().replace("ё", "е")


def sql_чисто(expr: str, p: dict, prefix: str = "чс") -> str:
    """Выражение: текст без хэштегов, эмодзи и ссылок, в одну строку. Регэкспы — параметрами."""
    out = expr
    for i, (rx, rep) in enumerate(_ЧИСТКА):
        p[f"{prefix}{i}"], p[f"{prefix}z{i}"] = rx, rep
        out = f"regexp_replace({out}, :{prefix}{i}, :{prefix}z{i}, 'gi')"
    return f"btrim({out})"


def sql_обрезать(expr: str, n: int, p: dict, prefix: str = "об") -> str:
    """Не длиннее n, по границе слова, с многоточием."""
    p[f"{prefix}хвост"] = r"\s+\S*$"
    return (f"CASE WHEN length({expr}) <= {n} THEN {expr} "
            f"ELSE regexp_replace(left({expr}, {n}), :{prefix}хвост, '') || '…' END")


def sql_шум(raw: str, clean: str, p: dict, prefix: str = "шм") -> str:
    """TRUE — не событие: дайджест, календарь, ежедневные курсы ЦБ (news_types.ШУМ) или котировка без слов."""
    p[f"{prefix}шум"], p[f"{prefix}буквы"], p[f"{prefix}мин"] = ШУМ, r"[^А-Яа-яЁёA-Za-z]", МИН_БУКВ
    return (f"(left({raw}, 160) ~* :{prefix}шум"
            f" OR length(regexp_replace({clean}, :{prefix}буквы, '', 'g')) < :{prefix}мин)")


def sql_теги_из_текста(expr: str, p: dict, prefix: str = "тт") -> str:
    """Хэштеги, вынутые из текста (у кандидата и сигнала нет колонки хэштегов), в нижнем регистре, ё → е."""
    p[f"{prefix}рх"] = r"(#[0-9A-Za-zА-Яа-яЁё_]+)"
    return (f"ARRAY(SELECT replace(lower(m[1]), 'ё', 'е') FROM regexp_matches(coalesce({expr}, ''), "
            f":{prefix}рх, 'g') m)")


def sql_теги(expr: str) -> str:
    """Колонка хэштегов (news_archive.hashtags) в нижнем регистре, ё → е: «#отчётность» = «#отчетность»."""
    return f"ARRAY(SELECT replace(lower(t), 'ё', 'е') FROM unnest(coalesce({expr}, CAST(ARRAY[] AS text[]))) t)"


def sql_тип(теги: str, текст: str, p: dict, prefix: str = "тп") -> tuple[str, str]:
    """Два CASE … END: тип по хэштегам и тип по словам (первое совпадение по порядку ТИПЫ). Хэштег автора надёжнее
    слов: «#регулирование … упрощение IPO» со словом «облигаций» — регулирование."""
    по_тегам, по_словам = [], []
    for i, (тип, теги_типа, rx) in enumerate(ТИПЫ):
        p[f"{prefix}h{i}"] = [норм_тег(t) for t in теги_типа] or ["#-"]
        p[f"{prefix}r{i}"], p[f"{prefix}n{i}"] = rx, тип
        по_тегам.append(f"WHEN {теги} && CAST(:{prefix}h{i} AS text[]) THEN CAST(:{prefix}n{i} AS text)")
        по_словам.append(f"WHEN {текст} ~* :{prefix}r{i} THEN CAST(:{prefix}n{i} AS text)")
    return "CASE " + " ".join(по_тегам) + " END", "CASE " + " ".join(по_словам) + " END"


def sql_правило(по_тегам: str, по_словам: str, p: dict, prefix: str = "тп") -> str:
    """Тип по правилам из двух проходов: хэштег, но событие по словам (ПЕРЕБИВАЮТ_СЫРЬЁ) главнее хэштега сырья.
    Аргументы — колонки, а не выражения: CASE по 24 типам повторять нельзя."""
    p[f"{prefix}сырьё"], p[f"{prefix}перебив"] = list(СЫРЬЁ_ТИПЫ), list(ПЕРЕБИВАЮТ_СЫРЬЁ)
    return (f"CASE WHEN {по_тегам} = ANY(CAST(:{prefix}сырьё AS text[])) AND {по_словам} = ANY(CAST(:{prefix}перебив AS text[]))"
            f" THEN {по_словам} ELSE COALESCE({по_тегам}, {по_словам}) END")


def sql_слова_за(тип: str, текст: str, p: dict, prefix: str = "тп") -> str:
    """TRUE, если в тексте есть горячие слова именно этого типа (для способа «хэштег+слова»). Параметры — из sql_тип."""
    ветки = " ".join(f"WHEN :{prefix}n{i} THEN {текст} ~* :{prefix}r{i}" for i in range(len(ТИПЫ)))
    return f"(CASE {тип} {ветки} ELSE FALSE END)"
