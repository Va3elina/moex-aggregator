ПЕРЕБИВАЮТ_СЫРЬЁ = ("удары по инфраструктуре", "налоги и бюджет")


def sql_type(alias: str, p: dict, prefix: str = "nt") -> str:
    """Выражение: тип по правилам (или NULL). У каждого типа — своя проверка «про наш рынок»: удар по иранскому танкеру
    не «удары по инфраструктуре» (они про нашу), а «нефть» — через мировые поставки. Регэкспы и теги — параметрами."""
    про_нас = _про_нас(alias, p, prefix)
    по_тегам, по_словам = [], []
    for i, (тип, теги, rx, где) in enumerate(ТИПЫ):
        p[f"{prefix}h{i}"], p[f"{prefix}r{i}"], p[f"{prefix}n{i}"] = теги or ["#-"], rx, тип
        # Хэштег автора надёжнее слов: «#регулирование … упрощение IPO» со словом «облигаций» — регулирование.
        по_тегам.append(f"WHEN {alias}.hashtags && CAST(:{prefix}h{i} AS text[]) AND {про_нас[где]} "
                        f"THEN CAST(:{prefix}n{i} AS text)")
        по_словам.append(f"WHEN {alias}.text ~* :{prefix}r{i} AND {про_нас[где]} THEN CAST(:{prefix}n{i} AS text)")
    p[f"{prefix}raw"], p[f"{prefix}beats"] = list(СЫРЬЁ_ТИПЫ), list(ПЕРЕБИВАЮТ_СЫРЬЁ)
    return (f"(SELECT CASE WHEN x.т = ANY(CAST(:{prefix}raw AS text[])) AND x.с = ANY(CAST(:{prefix}beats AS text[]))"
            f" THEN x.с ELSE COALESCE(x.т, x.с) END"
            f" FROM (SELECT CASE {' '.join(по_тегам)} END AS т, CASE {' '.join(по_словам)} END AS с) x)")


def sql_relevant(alias: str, p: dict, prefix: str = "nt") -> str:
    """Не шум: не дайджест и не ежедневные курсы, не мнение аналитиков, не обрывок."""
    p.update({f"{prefix}shum": ШУМ, f"{prefix}len": МИН_ДЛИНА})
    return (f"left({alias}.text, 160) !~* :{prefix}shum AND {alias}.text !~* '^[^а-яa-z]*мнение'"
            f" AND length({alias}.text) >= :{prefix}len")


def sql_topics(alias: str, p: dict, prefix: str = "nt") -> str:
    """Все темы новости (text[]), с компанией или без, — для связок завода (signals/insights/combos.py). Правила и проверка
    «про наш рынок» — те же, что у sql_type, но тема не одна главная: пост «Набиуллина: ставка… и курс рубля» питает и
    «ставку», и «рубль» (прогон связок 27.09: с одной темой терялся сюжет «рубль» 12.09). Мнение аналитиков тем не даёт
    (у мозга это отдельный тип). Короткую молнию («🔥ЦБ РФ снизил ставку до 17%») не отсекает, в отличие от sql_relevant:
    для связки она и есть главная новость дня. Шум (дайджест, календарь, реклама) отсекает вызывающий — vocab.sql_шум."""
    про_нас = _про_нас(alias, p, prefix)
    темы = []
    for i, (тип, теги, rx, где) in enumerate(ТИПЫ):
        p[f"{prefix}h{i}"], p[f"{prefix}r{i}"], p[f"{prefix}n{i}"] = теги or ["#-"], rx, тип
        темы.append(f"CASE WHEN ({alias}.hashtags && CAST(:{prefix}h{i} AS text[]) OR {alias}.text ~* :{prefix}r{i})"
                    f" AND {про_нас[где]} THEN CAST(:{prefix}n{i} AS text) END")
    return (f"CASE WHEN {alias}.text !~* '^[^а-яa-z]*мнение' THEN array_remove(ARRAY[{', '.join(темы)}], NULL)"
            f" ELSE CAST(ARRAY[] AS text[]) END")
