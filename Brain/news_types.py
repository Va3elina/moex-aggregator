def _про_нас(alias: str, p: dict, prefix: str) -> dict:
    p.update({f"{prefix}ru_t": РОССИЯ_ТЕГИ, f"{prefix}ru": РОССИЯ, f"{prefix}mir": СЫРЬЁ_МИР,
              f"{prefix}alien": ЧУЖИЕ_ТЕГИ, f"{prefix}abroad": ЗАРУБЕЖЬЕ, f"{prefix}sl": СМАРТЛАБ,
              f"{prefix}raw_t": СЫРЬЁ_ТЕГИ, f"{prefix}war": ВОЙНА})
    чужая = f"coalesce({alias}.hashtags, '{{}}') && CAST(:{prefix}alien AS text[])"
    смартлаб = f"({alias}.channel = ANY(CAST(:{prefix}sl AS text[])) AND {alias}.text !~* :{prefix}abroad)"
    россия = (f"({alias}.hashtags && CAST(:{prefix}ru_t AS text[])"
              f" OR ({alias}.text ~* :{prefix}ru AND NOT {чужая}) OR {смартлаб})")
    война = f"({alias}.text ~* :{prefix}war AND NOT {чужая})"
    мир = f"({alias}.text ~* :{prefix}mir OR {alias}.hashtags && CAST(:{prefix}raw_t AS text[]))"
    return {"россия": россия, "россия_и_война": f"({россия} OR {война})", "россия_или_мир": f"({россия} OR {мир})",
            "везде": "TRUE"}


