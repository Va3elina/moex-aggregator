"""Профиль стиля: чем черновик отличается от постов канала — числом, а не мнением.

⚠️ Зачем. Вадим 01.09: «у нас есть база примеров наших постов и сашиных — как мы их
оценивали, чтобы вывести формулу хорошего поста? может оценить размытым ощущением:
температура поста, частота и так далее».

Честный ответ на первую часть: формулу мы НЕ выводили. Мерились отдельные признаки,
и каждый — уже ПОСЛЕ его замечания. Плюс в корпусе нет оценок качества: известно, что
канал это опубликовал, но не какой пост хороший. Поэтому мерить можно «похоже на
канал», а не «хорошо» — и это надо помнить, читая любой скор отсюда.

Вторая часть идеи оказалась верной и сразу дала то, чего не поймало ни одно правило.

РЕЗУЛЬТАТ ПЕРВОГО ЗАМЕРА (жанровый срез канала n=44 / прежние черновики n=23 / v13):
    знаков                 661 / 881 / 393
    слов в предложении      11 /  18 /   9   ← попали
    хеджи                  11% / 61% /  0%   ← решено
    чисел на 100 знаков   0,40 / 1,13 / 1,35 ← стало ХУЖЕ
    доля предл. с числом  0,29 / 0,50 / 0,57 ← хуже
    температура (!+эмодзи) 1,00 / 0,80 / —   ← НЕ РАЗДЕЛЯЕТ, гипотеза не подтвердилась

Вывод, который иначе было не увидеть: убирая текст и оставляя факты, я поднял
плотность чисел втрое выше канала. У канала 661 знак с МАЛЫМ числом цифр — есть
проза и связки. У нас 393 знака почти целиком из чисел. Вырезана соединительная
ткань, а не числа.

⚠️ Чем это лучше судьи: детерминировано и бесплатно. Судья — сам LLM, и его вердикт
плавает (01.09: один и тот же текст получил «брак», потом «годится»). Профиль на том
же тексте всегда даёт одно и то же.
⚠️ Чем хуже: похожесть на канал ≠ качество. Идеально «канальный» пост может быть
скучным или неверным по фактам. Профиль дополняет судью, а не заменяет его.

Использование:
    python -m research.content_pipeline_v2.style_profile            # эталон канала
    python -m research.content_pipeline_v2.style_profile файл.txt   # оценить черновик
"""
import gzip
import json
import re
import statistics as st
import sys
from pathlib import Path

DATA = Path(__file__).parent / "dataset"
GENRE = ("#открытыйинтерес", "#открытыепозиции")

_EMO = re.compile(r"[\U0001F300-\U0001FAFF☀-➿]")
_HEDGE = re.compile(r"(стоит последить|покажут ближайш|не приговор|время покажет"
                    r"|вероятно|возможно|скорее всего)", re.I)
# Признаки, которые РАЗДЕЛЯЮТ канал и черновики. Остальные померены и отброшены:
# эмодзи, температура, число абзацев и предложений в абзаце совпадают у обоих.
KEYS = ("знаков", "слов_в_предл", "чисел_на_100зн", "доля_предл_с_числом")


def _paras(t: str) -> list:
    """Абзацы без заголовка-подписи и хэштегов.

    ⚠️ Подпись @FrameTool обязательно снимать: без этого «последним абзацем» у
    опубликованных постов оказывается она, и весь замер даёт нули (наступал 01.09).
    """
    return [x.strip() for x in (t or "").split("\n")
            if x.strip() and not x.strip().startswith("#")
            and "@FrameTool" not in x and len(re.sub(r"[\W_]", "", x)) > 8]


def profile(text: str):
    paras = _paras(text)
    if not paras:
        return None
    body = " ".join(paras)
    sents = [s for p in paras for s in re.split(r"(?<=[.!?])\s+", p) if len(s.split()) > 1]
    if not sents:
        return None
    nums = re.findall(r"\d+[,.]?\d*", body)
    return {
        "знаков": len(text),
        "абзацев": len(paras),
        "слов_в_предл": st.median([len(s.split()) for s in sents]),
        "чисел_на_100зн": 100 * len(nums) / max(len(body), 1),
        "доля_предл_с_числом": sum(bool(re.search(r"\d", s)) for s in sents) / len(sents),
        "температура": (text.count("!") + len(_EMO.findall(text))) / len(paras),
        "хедж": bool(_HEDGE.search(body)),
    }


def channel_reference():
    """Эталон по жанровому срезу канала: медиана и разброс по каждому признаку."""
    posts = json.load(gzip.open(DATA / "corpus.json.gz", "rt", encoding="utf-8"))
    prof = [p for p in (profile(x["text"]) for x in posts
                        if any(h in (x.get("text") or "") for h in GENRE)) if p]
    return ({k: st.median([x[k] for x in prof]) for k in KEYS},
            {k: st.stdev([x[k] for x in prof]) for k in KEYS}, len(prof))


def score(text: str):
    """Отклонение от профиля канала в сигмах по каждому признаку и в среднем.

    Меньше — ближе к каналу. Знак показывает направление: плюс — больше канала.
    """
    ref, sd, n = channel_reference()
    p = profile(text)
    if not p:
        return None
    dev = {k: (p[k] - ref[k]) / sd[k] for k in KEYS}
    return {"профиль": p, "эталон": ref, "отклонение_сигм": dev,
            "среднее_отклонение": st.mean(abs(v) for v in dev.values()), "n_эталона": n}


def _fmt(res) -> str:
    out = [f"эталон канала: n={res['n_эталона']}", ""]
    for k in KEYS:
        out.append(f"  {k:22} {res['профиль'][k]:8.2f}   эталон {res['эталон'][k]:7.2f}"
                   f"   {res['отклонение_сигм'][k]:+.2f}σ")
    out += ["", f"  среднее отклонение: {res['среднее_отклонение']:.2f}σ",
            "  (похожесть на канал, НЕ качество — см. докстринг модуля)"]
    return "\n".join(out)


if __name__ == "__main__":
    if len(sys.argv) > 1:
        res = score(Path(sys.argv[1]).read_text("utf-8"))
        print(_fmt(res) if res else "не удалось разобрать текст")
    else:
        ref, sd, n = channel_reference()
        print(f"эталон жанрового среза канала (n={n}):")
        for k in KEYS:
            print(f"  {k:22} медиана {ref[k]:8.2f}  ±{sd[k]:.2f}")
