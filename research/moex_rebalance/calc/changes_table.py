#!/usr/bin/env python
"""Что изменилось у КАЖДОЙ бумаги Индекса МосБиржи: FF, LW и их произведение.

Без всяких оценок сделок — только коэффициенты. Пишет ../CHANGES.md.

Смысл произведения FF × LW. По п. 2.7.2 методики LW определён как отношение доли
реально доступных к торгам акций (в НРД, за исключением счетов типа «С») к самому
коэффициенту free-float. Значит:

    FF × LW  =  доля акций, реально доступных к торгам

и именно это произведение, а не FF по отдельности, входит в вес. Поэтому подъём FF без
роста доступности механически тянет LW вниз, и вес не меняется.

⚠️ LW «сейчас» приходится ВОССТАНАВЛИВАТЬ. Биржа публикует только новую таблицу LW;
действующая отдельно не публикуется. Из ISS приходит w_factor = WW × LW (п. 2.8.5).
  • если w_factor — круглое кратное 0,1, значит WW = 1 (потолок бумагу не жмёт)
    и LW = w_factor ТОЧНО. Так у 43 бумаг из 46.
  • если знаков много (0,5332875) — бумагу режет потолок, и тогда w_factor про LW не
    говорит НИЧЕГО. Показать это несложно: при сработавшем потолке итоговый вес равен
    15% по построению, отсюда числитель A = 0,17647 × (сумма остальных), а он же равен
    cap × FF × w_factor. То есть w_factor определён наблюдаемыми величинами, и LW из
    уравнения сокращается. Единственная жёсткая граница — LW ≥ w_factor (так как WW ≤ 1).

Как тогда получить LW у бумаг под потолком (их три: ЛУКОЙЛ, Сбербанк-ао, Сбербанк-ап):
  1. Взять его из НОВОЙ опубликованной таблицы, если бумага там есть, и считать, что
     значение не менялось. Так получены Сбербанк-ао 0,3 и Сбербанк-ап 0,6 — и оба
     согласуются с границей: 0,3 ≥ 0,2502686 и 0,6 ≥ 0,5005372.
  2. Если бумаги в новой таблице нет, её новый LW = 1 по правилу «кого нет — у того
     единица». Для действующего значения ищем в истории период, когда потолок бумагу
     НЕ жал: там w_factor круглый и равен самому LW. У ЛУКОЙЛа такой период нашёлся —
     декабрь 2022 в индексе широкого рынка, w_factor ровно 1,0. Значит LW = 1,0, и
     ограничения на доступность у него не было никогда.

     ⚠️ Прежняя версия этого скрипта брала «ближайшее сверху кратное 0,1», то есть 0,6,
     и давала ЛУКОЙЛу рост доступной доли ×1,79 вместо ×1,07. Ошибка в том, что
     ближайшая сверху граница — это МИНИМУМ из возможных, а не значение.

Запуск:  .venv/bin/python research/moex_rebalance/calc/changes_table.py
"""
from __future__ import annotations

import json
import pathlib
import sys

BASE = pathlib.Path(__file__).resolve().parents[1]
DATA = BASE / "data"
ASOF = "2026-09-01"

# Действующий LW у бумаг, которые режет потолок (для них w_factor ≠ LW, см. шапку файла).
# ЛУКОЙЛ: доказано историей — в индексе широкого рынка в декабре 2022 его w_factor был
# ровно 1,0, то есть WW = 1 и LW = 1,0. В Индексе МосБиржи он под потолком всегда, там
# это значение не увидеть. LW — свойство бумаги, не индекса (п. 2.7.2), поэтому
# наблюдение из другого индекса переносится.
# Сбербанк: взято из новой опубликованной таблицы в предположении, что значение не
# менялось; обе величины совместимы с границей LW ≥ w_factor.
LW_CAPPED = {"LKOH": 1.0, "SBER": 0.3, "SBERP": 0.6}
EXCLUDED = {"LENT": "Лента", "MSNG": "Мосэнерго"}

RU = {
    "AFKS": "АФК Система", "AFLT": "Аэрофлот", "ALRS": "АЛРОСА", "BSPB": "Банк Санкт-Петербург",
    "CBOM": "МКБ", "CHMF": "Северсталь", "CNRU": "ЦИАН", "DOMRF": "ДОМ.РФ", "ENPG": "ЭН+",
    "FLOT": "Совкомфлот", "GAZP": "Газпром", "GMKN": "Норникель", "HEAD": "Хэдхантер",
    "IRAO": "Интер РАО", "LENT": "Лента", "LKOH": "ЛУКОЙЛ", "MAGN": "ММК",
    "MDMG": "Мать и дитя", "MOEX": "Московская Биржа", "MSNG": "Мосэнерго", "MTSS": "МТС",
    "NLMK": "НЛМК", "NVTK": "Новатэк", "OZON": "Озон", "PHOR": "ФосАгро", "PLZL": "Полюс",
    "POSI": "Группа Позитив", "RAGR": "Русагро", "RENI": "Ренессанс Страхование",
    "ROSN": "Роснефть", "RTKM": "Ростелеком, ао", "RUAL": "РУСАЛ", "SBER": "Сбербанк, ао",
    "SBERP": "Сбербанк, ап", "SNGS": "Сургутнефтегаз, ао", "SNGSP": "Сургутнефтегаз, ап",
    "SVCB": "Совкомбанк", "T": "Т-Технологии", "TATN": "Татнефть, ао", "TATNP": "Татнефть, ап",
    "TRNFP": "Транснефть, ап", "UGLD": "ЮГК", "VKCO": "ВК", "VTBR": "ВТБ", "X5": "X5",
    "YDEX": "Яндекс",
}


def fmt(x: float | None, digits: int = 2) -> str:
    if x is None:
        return "—"
    return f"{x:.{digits}f}".replace(".", ",")


def main() -> int:
    iss = json.loads((DATA / "iss_imoex.json").read_text(encoding="utf-8"))["бумаги"]
    lw_new = json.loads((DATA / "lw_new.json").read_text(encoding="utf-8"))
    ff_new = json.loads((DATA / "ff_new.json").read_text(encoding="utf-8"))
    assert len(lw_new) == 60 and len(ff_new) == 15

    rows = []
    for t, v in iss.items():
        if ASOF not in v or not v[ASOF]["ff"] or not v[ASOF]["w"]:
            continue
        ff_o, w_o = v[ASOF]["ff"], v[ASOF]["w"]
        round_w = abs(w_o * 10 - round(w_o * 10)) < 1e-9
        ff_n = ff_new.get(t, ff_o)
        lw_n = lw_new.get(t, 1.0)
        if round_w:
            lw_o = w_o                      # WW = 1, значение видно напрямую
        else:
            # бумага под потолком: w_factor про LW не говорит ничего, кроме LW ≥ w_factor.
            # берём опубликованное новое значение (для тех, кто в таблице) либо доказанное
            # по истории (ЛУКОЙЛ, см. шапку файла), и проверяем совместимость с границей.
            lw_o = LW_CAPPED.get(t, lw_n)
            assert lw_o >= w_o - 1e-9, f"{t}: LW {lw_o} меньше w_factor {w_o} — WW вышел бы >1"
        rows.append({
            "код": t, "имя": RU.get(t, t),
            "вес": v[ASOF]["weight"],
            "ff_o": ff_o, "ff_n": ff_n,
            "lw_o": lw_o, "lw_n": lw_n, "lw_точно": round_w,
            "w_factor": w_o,
            "в_таблице_lw": t in lw_new,
            "ff_изм": abs(ff_n - ff_o) > 1e-9,
            "lw_изм": abs(lw_n - lw_o) > 1e-9,
            "дост_o": ff_o * lw_o, "дост_n": ff_n * lw_n,
            "уходит": t in EXCLUDED,
        })
    rows.sort(key=lambda r: -r["вес"])

    L = []
    p = L.append
    p("# Что изменилось у каждой бумаги индекса\n")
    p(f"Сгенерировано `calc/changes_table.py` по данным на **{ASOF}**. "
      f"Бумаг в Индексе МосБиржи: **{len(rows)}**. Никаких оценок сделок — только "
      f"коэффициенты.\n")
    p("## Как читать\n")
    p("`FF` — коэффициент free-float, доля акций в свободном обращении по критерию "
      "собственности. Публикуется в пресс-релизе.\n")
    p("`LW` — дополнительный весовой коэффициент, поправка на **доступность**: сколько из "
      "формально свободных акций реально можно купить. Публикуется отдельным файлом "
      "к релизу, кого в файле нет — у того LW = 1.\n")
    p("`Wi` — **коэффициент, ограничивающий вес**, из официальной таблицы состава индекса. "
      "Это НЕ то же самое, что LW: по п. 2.8.5 `Wi = WWi × LWi`, где `WWi` обеспечивает "
      "потолки и нигде не публикуется. У 43 бумаг из 46 потолок не жмёт, `WWi = 1`, и тогда "
      "`Wi` равен самому LW. У трёх (ЛУКОЙЛ и оба класса Сбербанка) `Wi` дробный — там "
      "сидит `WWi`.\n")
    p("⚠️ **Нового `Wi` в релизе нет и быть не может**: биржа публикует FF и LW, а `WWi` "
      "считает сама по итогам дня перед раскрытием. Поэтому сравнивать «было → станет» "
      "корректно по `FF` и `LW`, а не по `Wi`.\n")
    p("`FF × LW` — **доля реально доступных к торгам акций**, и это собственный эффект "
      "бумаги, без потолков. Именно его надо смотреть, а не FF по отдельности.\n")
    p("Столбец «×» — во сколько раз изменилось произведение. Больше 1 — бумага "
      "потяжелеет, меньше — полегчает, ровно 1 — ничего не изменилось.\n")
    p("Пометка `восст.` у LW стоит у трёх бумаг, которые режет потолок: у них `w_factor` "
      "из ISS равен произведению WW × LW и сам по себе про LW не говорит ничего. "
      "Для Сбербанка значение взято из новой опубликованной таблицы, для ЛУКОЙЛа — "
      "из декабря 2022, когда потолок его не жал и `w_factor` был ровно 1,0. "
      "У остальных 43 бумаг `w_factor` кратен 0,1, то есть WW = 1 и LW виден напрямую.\n")

    ch = [r for r in rows if (r["ff_изм"] or r["lw_изм"]) and not r["уходит"]]
    same = [r for r in rows if not r["ff_изм"] and not r["lw_изм"] and not r["уходит"]]
    out = [r for r in rows if r["уходит"]]

    # Полная таблица: ВСЕ бумаги индекса в одном месте, по убыванию веса.
    # Разбивка по группам ниже — та же таблица, просто отсортированная по смыслу.
    p(f"\n## 0. Все {len(rows)} бумаг индекса\n")
    p("Столбец «что» : `—` коэффициенты не трогали · `FF` менялся только free-float · "
      "`LW` только доп. коэффициент · `FF+LW` оба · `уходит` покидает индекс.\n")
    p("| # | бумага | вес | FF было | FF станет | Wi сейчас | LW сейчас | LW с 18.09 | "
      "FF×LW было | FF×LW станет | × | что |")
    p("|---|---|---|---|---|---|---|---|---|---|---|---|")
    for i, r in enumerate(rows, 1):
        if r["уходит"]:
            what, rate = "уходит", "0,00"
        else:
            what = ("FF+LW" if r["ff_изм"] and r["lw_изм"]
                    else "FF" if r["ff_изм"] else "LW" if r["lw_изм"] else "—")
            rate = fmt(r["дост_n"] / r["дост_o"])
        mark = "" if r["lw_точно"] else "*"
        wi = fmt(r["w_factor"], 7).rstrip("0").rstrip(",") if not r["lw_точно"] \
             else fmt(r["w_factor"], 1)
        p(f"| {i} | {r['имя']} ({r['код']}) | {fmt(r['вес'])}% "
          f"| {fmt(r['ff_o'] * 100, 0)}% | {fmt(r['ff_n'] * 100, 0)}% "
          f"| {wi} "
          f"| {fmt(r['lw_o'], 1)}{mark} | {fmt(r['lw_n'], 1)} "
          f"| {fmt(r['дост_o'] * 100, 1)}% | {fmt(r['дост_n'] * 100, 1)}% "
          f"| {rate} | {what} |")
    unc = [r for r in rows if not r["lw_точно"]]
    who = ", ".join(f"{r['имя']} (w_factor {fmt(r['w_factor'], 7)}, принят LW {fmt(r['lw_o'], 1)})"
                    for r in unc)
    p("\n⚠️ **Диапазон, а не значение.** У ЛУКОЙЛа строго исключены только `LW ≤ 0,5` "
      "(процедура потолков) и `LW = 0,6` (граница `WW ≤ 1` по базе марта-2026). Значения "
      "0,7 / 0,8 / 0,9 формально не закрыты — прецедент смены LW при выросшем FF есть "
      "(Ренессанс: 0,9 → 1,0). Тогда доступная доля меняется ×1,53 / ×1,34 / ×1,19 вместо "
      "×1,07. Принято 1,0: прямое чтение из истории (базы 2022 года), заявление релиза о "
      "техническом характере правок LW и то, что при росте FF компенсация идёт вниз, а 1,0 "
      "— максимум. **На рублёвые оценки выбор не влияет**: для упёршейся в потолок бумаги "
      "новый вес от LW не зависит вовсе.\n")
    p(f"\n`*` — бумага под потолком, поэтому `w_factor` = WW × LW и сам LW из него не "
      f"читается; значение взято из внешнего свидетельства (см. шапку скрипта). "
      f"Таких бумаг {len(unc)}: {who}. "
      f"У остальных {len(rows) - len(unc)} `w_factor` кратен 0,1 ⇒ WW = 1 и LW равен ему точно.\n")

    p(f"\n## 1. Изменения есть: {len(ch)} бумаг\n")
    p("| бумага | вес сейчас | FF было → станет | LW сейчас → с 18.09 | FF×LW было → станет | × |")
    p("|---|---|---|---|---|---|")
    for r in sorted(ch, key=lambda r: -(r["дост_n"] / r["дост_o"])):
        mark = "" if r["lw_точно"] else " `восст.`"
        rate = r["дост_n"] / r["дост_o"]
        p(f"| **{r['имя']}** ({r['код']}) | {fmt(r['вес'])}% "
          f"| {fmt(r['ff_o'] * 100, 0)}% → {fmt(r['ff_n'] * 100, 0)}% "
          f"| {fmt(r['lw_o'], 1)}{mark} → {fmt(r['lw_n'], 1)} "
          f"| {fmt(r['дост_o'] * 100, 1)}% → {fmt(r['дост_n'] * 100, 1)}% "
          f"| **{fmt(rate)}** |")

    p(f"\n## 2. Ничего не изменилось: {len(same)} бумаг\n")
    p("У этих бумаг ни free-float, ни LW не трогали — их вес сдвинется только за счёт "
      "перераспределения освободившихся долей.\n")
    p("| бумага | вес | FF | LW | FF×LW |")
    p("|---|---|---|---|---|")
    for r in same:
        mark = "" if r["lw_точно"] else " `восст.`"
        p(f"| {r['имя']} ({r['код']}) | {fmt(r['вес'])}% | {fmt(r['ff_o'] * 100, 0)}% "
          f"| {fmt(r['lw_o'], 1)}{mark} | {fmt(r['дост_o'] * 100, 1)}% |")

    p(f"\n## 3. Уходят из индекса: {len(out)} бумаги\n")
    p("Для них коэффициенты не имеют значения: бумага покидает базу расчёта, вес "
      "становится нулём независимо от FF и LW.\n")
    p("| бумага | вес сейчас | FF | LW сейчас | LW в новой таблице |")
    p("|---|---|---|---|---|")
    for r in out:
        p(f"| **{r['имя']}** ({r['код']}) | {fmt(r['вес'])}% | {fmt(r['ff_o'] * 100, 0)}% "
          f"| {fmt(r['lw_o'], 1)} "
          f"| {'есть, ' + fmt(r['lw_n'], 1) if r['в_таблице_lw'] else 'нет'} |")

    # сводка по направлениям
    up = [r for r in ch if r["дост_n"] > r["дост_o"] * 1.001]
    down = [r for r in ch if r["дост_n"] < r["дост_o"] * 0.999]
    flat = [r for r in ch if r not in up and r not in down]
    p("\n## Итог по направлениям\n")
    p(f"- **доступная доля выросла** — {len(up)} бумаг: "
      f"{', '.join(r['имя'] for r in up)}")
    p(f"- **упала** — {len(down)} бумаг: {', '.join(r['имя'] for r in down)}")
    p(f"- **не изменилась при изменившихся коэффициентах** — {len(flat)} бумаг: "
      f"{', '.join(r['имя'] for r in flat) or '—'}")
    p(f"- коэффициенты не трогали — {len(same)} бумаг")
    p(f"- уходят из индекса — {len(out)}: {', '.join(r['имя'] for r in out)}")

    # ── Раздел 4: перераспределение ────────────────────────────────────────────
    tw_path = DATA / "trades_by_weight.json"
    if tw_path.exists():
        tw = json.loads(tw_path.read_text(encoding="utf-8"))
        W, norm = tw["веса"], tw["нормировка"]
        p("\n## 4. Перераспределение: кто получает освободившийся вес\n")
        p("Освободившийся вес не «раздаётся» — он появляется через нормировку. Суммарная "
          f"учитываемая капитализация индекса падает в **{fmt(norm, 4)}** раза (уходят Лента "
          "и Мосэнерго, урезают ЛУКОЙЛа и Сбербанка), а значит доля каждой оставшейся бумаги "
          f"в меньшем знаменателе автоматически растёт: **×{fmt(1 / norm, 4)}**, то есть "
          f"**{fmt(100 * (1 / norm - 1), 2)}%**. Это одно число на всех.\n")
        p("Но по п. 2.8.4 разница распределяется «между Эмитентами, Удельные веса которых "
          "**не были ограничены**». Поэтому у эмитентов под потолком перераспределения нет "
          "вовсе — их вес задан потолком, и раскладывать его на слагаемые бессмысленно: "
          "`WW` не независимый множитель, а остаток, подобранный под ответ.\n")
        p("| бумага | вес сейчас | своё, × | своё, п.п. | перераспр., п.п. | итого | вес новый |")
        p("|---|---|---|---|---|---|---|")
        rows2 = sorted((t for t in W if t in {r["код"] for r in rows}),
                       key=lambda t: -abs(W[t]["new"] - W[t]["old"]))
        for t in rows2[:18]:
            v = W[t]
            tot_ = v["new"] - v["old"]
            if v["обрезан"]:
                p(f"| **{RU.get(t, t)}** | {fmt(v['old'])}% | — | — | — "
                  f"| **{fmt(tot_)}** | {fmt(v['new'])}% |  ← вес задан потолком |")
                continue
            # вес_нов/вес_стар = своё × (1/нормировка) ⇒ своё = вес_нов × нормировка / вес_стар.
            # Делил вместо умножения — у нетронутых бумаг «своё» выходило ×1,055 вместо ×1,000.
            r_own = (v["new"] * norm) / v["old"] if v["old"] else 0
            own = v["old"] * (r_own - 1)
            p(f"| {RU.get(t, t)} | {fmt(v['old'])}% | {fmt(r_own, 3)} | {fmt(own)} "
              f"| {fmt(tot_ - own)} | {fmt(tot_)} | {fmt(v['new'])}% |")
        cap_list = " · ".join(RU.get(t, t) for t in W if W[t]["обрезан"])
        p(f"\nУ эмитентов под потолком ({cap_list}) `WW` меньше единицы: "
          f"{' · '.join(f'{RU.get(t, t)} = {fmt(W[t][chr(119) + chr(119)], 4)}' for t in W if W[t]['обрезан'])}. "
          f"У остальных он **ровно 1,0** — п. 2.8.6 не допускает больше единицы.\n")

    (BASE / "CHANGES.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))
    return 0


if __name__ == "__main__":
    sys.exit(main())
