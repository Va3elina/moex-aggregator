/**
 * Глобальный выключатель ENTRANCE-анимаций графиков (reveal линии, волна
 * баров, рост кругляшей/пончика).
 *
 * Зачем: в ПЕСОЧНИЦЕ панели живут в одном окне и монтируются заново при любом
 * ⤢/свернуть (развёрнутая панель рендерится в отдельном поддереве .sb-max, а
 * сетка на это время не рендерится вовсе). React-ремонт = «первый рендер с
 * данными» = entrance-анимация играет заново — сразу на ВСЕХ панелях. В
 * терминальной раскладке это читается как «всё перезагрузилось».
 *
 * Поэтому SandboxPage оборачивает своё дерево в <NoChartAnimCtx.Provider
 * value>. На сайте/в embed'ах контекста нет → false → анимации как были.
 *
 * Морф данных (смена бумаги/периода) НЕ трогаем: это переход между двумя
 * состояниями, а не появление, и он не связан с ремонтом.
 */
import { createContext, useContext } from 'react';

export const NoChartAnimCtx = createContext(false);

/** true — entrance-анимации графиков выключены (песочница). */
export function useNoChartAnim(): boolean {
  return useContext(NoChartAnimCtx);
}
