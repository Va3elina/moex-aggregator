/**
 * Дефолтная видимость категорий участников на /cbr-flows. До 7 участников
 * (stocks/ofz) не помещаются на мобилке — сужаем стартовый набор до базовых
 * категорий, остальные скрыты, но остаются доступны в selector'е категорий.
 * Полный порядок зеркалит бэкенд (api/routers/cbr_flows.py::CATEGORY_ORDER).
 */
type CbrType = 'stocks' | 'ofz' | 'fx';

const ALL_CATEGORIES: Record<CbrType, string[]> = {
  stocks: [
    'Физические лица', 'Доверительное управление', 'Нерезиденты',
    'НФО', 'Прочие Банки', 'СЗКО', 'Нефинансовые организации',
  ],
  ofz: [
    'Физические лица', 'Доверительное управление', 'Нерезиденты',
    'НФО', 'Прочие Банки', 'СЗКО', 'Нефинансовые организации',
  ],
  fx: [
    'Физические лица', 'Клиенты российских кредитных организаций',
    'НФО', 'Банк России', 'Российские кредитные организации',
  ],
};

const DEFAULT_VISIBLE: Record<CbrType, string[]> = {
  stocks: ['Физические лица', 'Нерезиденты', 'Доверительное управление'],
  ofz: ['Физические лица', 'Нерезиденты', 'Доверительное управление'],
  fx: ['Физические лица', 'НФО', 'Банк России', 'Клиенты российских кредитных организаций'],
};

/** Категории, скрытые по умолчанию для первого визита (остальное — базовые). */
export function getDefaultHiddenCategories(type: CbrType): Set<string> {
  const visible = new Set(DEFAULT_VISIBLE[type]);
  return new Set(ALL_CATEGORIES[type].filter((c) => !visible.has(c)));
}
