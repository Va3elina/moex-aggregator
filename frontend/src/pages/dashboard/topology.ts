/**
 * Топология проекта: узлы и рёбра карты «откуда что течёт».
 *
 * ⚠️ ЭТО АВТОРСКОЕ ЗНАНИЕ, А НЕ ВЫВОДИМОЕ. Из базы можно узнать, что пайплайн
 * `funds_daily` вчера отработал за 12 секунд, но НЕЛЬЗЯ узнать, что он ходит в
 * Cbonds и пишет в fund_data. Эта связь живёт только в коде фетчера и в голове.
 * Карта её и фиксирует: узлы и рёбра здесь заданы руками, а живое состояние
 * приезжает из pipeline_runs и подставляется по именам в `пайплайны`.
 *
 * ⚠️ КООРДИНАТЫ ЗАДАНЫ ЯВНО, БЕЗ РАСКЛАДКИ СИЛАМИ. Силовая раскладка каждый раз
 * рисует чуть другую картинку и дёргается при обновлении — на приборной панели,
 * которую открывают по десять раз в день, узлы должны лежать там же, где вчера.
 * Плюс это ноль вычислений в браузере: экран не имеет права тормозить.
 *
 * Как добавить фетчер: дописать его имя в `пайплайны` нужного узла обработки.
 * Имя должно совпадать с `pipeline` в pipeline_runs — иначе узел останется серым.
 */

export type ВидУзла = 'источник' | 'обработка' | 'хранилище' | 'витрина';

export interface УзелКарты {
  id: string;
  вид: ВидУзла;
  имя: string;
  /** Вторая строка: чем является или откуда берёт. */
  подпись: string;
  /**
   * Подробности, раскрываются по клику. Здесь живёт то, что на узел не влезает:
   * конкретные адреса и каналы, расписание, чем опасен сбой. Без этого карта
   * говорит «Telegram · 1 процесс» там, где за узлом два канала, два скрипта и
   * два разных транспорта.
   */
  детали?: string[];
  /** Имена пайплайнов из pipeline_runs. Состояние узла = худшее среди них. */
  пайплайны: string[];
  x: number;
  y: number;
}

export interface РеброКарты {
  от: string;
  к: string;
  /** Пунктиром рисуем то, что идёт не по расписанию, а руками. */
  ручное?: boolean;
}

