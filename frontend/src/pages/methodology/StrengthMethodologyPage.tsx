/**
 * StrengthMethodologyPage — подробная методология «Сила рынка».
 *
 * Принципы (как во всех методологиях):
 *   - НЕ раскрываем формулы (что такое средняя линия, её период, порог зон) —
 *     объясняем только СМЫСЛ: «доля акций выше своей средней линии».
 *   - Без англицизмов, без торговых советов.
 *   - Источник — только Московская биржа (публичные данные).
 *   - Инфографика — встроенный SVG в стиле OI-инфографик: currentColor для
 *     нейтральных элементов, GREEN/RED/ACCENT для смысла.
 */
