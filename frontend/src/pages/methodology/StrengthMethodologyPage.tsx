/* ── Инфографика 1: суть индикатора — доля акций выше своей средней линии ──── */
function BreadthShareFigure() {
  // 10 акций: каждая — своя цена (точка) и своя средняя линия (чёрточка).
  // above=true → цена выше линии (зелёная), false → ниже (красная). 7 из 10 выше.
  const cols = [
    { above: true }, { above: true }, { above: false }, { above: true }, { above: true },
    { above: false }, { above: true }, { above: true }, { above: false }, { above: true },
  ];
  const x0 = 20;
  const step = 28;
  const lineY = 60; // «средняя линия» акции — общий ориентир на схеме
  return (
    <Figure
      caption={
        <>
          Каждая акция сравнивается со <b>своей средней линией</b>. Здесь <b>7 из 10</b> акций
          стоят выше — значит «Сила рынка» = <b>70%</b>. Индикатор считает только долю, а не насколько именно выше.
        </>
      }
    >
      <svg viewBox="0 0 320 118" style={{ width: '100%', display: 'block' }} role="img" aria-label="Доля акций выше своей средней линии">
        {cols.map((c, i) => {
          const cx = x0 + i * step;
          const dotY = c.above ? lineY - 18 : lineY + 18;
          const color = c.above ? GREEN : RED;
          return (
            <g key={i}>
              {/* черта «средняя линия» этой акции */}
              <line x1={cx - 8} y1={lineY} x2={cx + 8} y2={lineY} stroke="currentColor" strokeWidth="1.4" opacity="0.4" />
              {/* стойка от линии к цене */}
              <line x1={cx} y1={lineY} x2={cx} y2={dotY} stroke={color} strokeWidth="1.4" opacity="0.6" />
              {/* точка «цена акции» */}
              <circle cx={cx} cy={dotY} r="5" fill={color} />
            </g>
          );
        })}
        <text x={x0 - 6} y="20" fontSize="10" fontWeight="700" fill={GREEN}>выше линии</text>
        <text x={x0 - 6} y="112" fontSize="10" fontWeight="700" fill={RED}>ниже линии</text>
        <text x="300" y="66" textAnchor="end" fontSize="10" fill="currentColor" opacity="0.7">= 70%</text>
      </svg>
    </Figure>
  );
}

/* ── Инфографика 2: широкий рост vs узкий рост (та же цена индекса) ───────── */
function BroadVsNarrowFigure() {
  return (
    <Figure
      caption={
        <>
          Индекс может расти <b>двумя способами</b>. Слева тянут почти все бумаги — рост широкий и здоровый.
          Справа индекс держат <b>пара тяжеловесов</b>, остальное падает — «Сила рынка» низкая, движение хрупкое.
        </>
      }
    >
      <svg viewBox="0 0 320 128" style={{ width: '100%', display: 'block' }} role="img" aria-label="Широкий рост против узкого роста">
        {/* Левая панель — широкий рост */}
        <text x="70" y="16" textAnchor="middle" fontSize="10.5" fontWeight="700" fill={GREEN}>широкий рост</text>
        {[0, 1, 2, 3, 4, 5].map((i) => {
          const up = i !== 2; // почти все растут
          const x = 22 + i * 18;
          const h = up ? 30 + (i % 3) * 8 : 16;
          return <rect key={i} x={x} y={90 - h} width="11" height={h} rx="2" fill={up ? GREEN : RED} opacity={up ? 0.85 : 0.7} />;
        })}
        <text x="70" y="106" textAnchor="middle" fontSize="9" fill="currentColor" opacity="0.7">растёт большинство</text>
        {/* стрелка индекса вверх */}
        <text x="70" y="122" textAnchor="middle" fontSize="10" fontWeight="700" fill={ACCENT}>индекс ↑</text>

        {/* разделитель */}
        <line x1="160" y1="10" x2="160" y2="120" stroke="currentColor" strokeWidth="1" strokeDasharray="3 3" opacity="0.3" />

        {/* Правая панель — узкий рост */}
        <text x="250" y="16" textAnchor="middle" fontSize="10.5" fontWeight="700" fill={RED}>узкий рост</text>
        {[0, 1, 2, 3, 4, 5].map((i) => {
          const up = i === 4; // растёт один «тяжеловес»
          const x = 202 + i * 18;
          const h = up ? 58 : 14 + (i % 3) * 4;
          return <rect key={i} x={x} y={90 - h} width="11" height={h} rx="2" fill={up ? GREEN : RED} opacity={up ? 0.9 : 0.7} />;
        })}
        <text x="250" y="106" textAnchor="middle" fontSize="9" fill="currentColor" opacity="0.7">тянут единицы</text>
        <text x="250" y="122" textAnchor="middle" fontSize="10" fontWeight="700" fill={ACCENT}>индекс ↑</text>
      </svg>
    </Figure>
  );
}

/* ── Инфографика 3: цветовая шкала значения 0…100 (как в гистограмме/тултипе) ─ */
