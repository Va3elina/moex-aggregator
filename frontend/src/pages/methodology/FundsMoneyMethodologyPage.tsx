/**
 * Притоки-Оттоки: гистограмма чистого движения денег. Зелёное вверх =
 * пришло, красное вниз = ушло. Очищено от движения котировок.
 */
function FlowsHistogramFigure() {
  // столбики: значение в условных единицах, знак = направление
  const bars = [3, 5, 2, -2, -4, 6, 4, -1, 7, -3];
  const bw = 20;
  const gap = 8;
  const zeroY = 60;
  const scale = 6;
  return (
    <Figure
      maxWidth={340}
      caption={
        <>
          Каждый столбик — чистое движение денег за шаг.{' '}
          <span style={{ color: GREEN, fontWeight: 700 }}>Вверх — приток</span> (внесли больше, чем забрали),{' '}
          <span style={{ color: RED, fontWeight: 700 }}>вниз — отток</span>. Рост котировок сюда не попадает.
        </>
      }
    >
      <svg viewBox="0 0 300 130" xmlns="http://www.w3.org/2000/svg" style={{ width: '100%', height: 'auto' }}>
        {/* нулевая линия */}
        <line x1="16" y1={zeroY} x2="284" y2={zeroY} stroke="currentColor" strokeWidth="1.2" opacity="0.5" />
        <text x="288" y={zeroY + 3} fontSize="9" fill="currentColor" opacity="0.6">0</text>

        {bars.map((v, i) => {
          const x = 24 + i * (bw + gap);
          const h = Math.abs(v) * scale;
          const y = v >= 0 ? zeroY - h : zeroY;
          return (
            <rect
              key={i}
              x={x}
              y={y}
              width={bw}
              height={h}
              rx="2.5"
              fill={v >= 0 ? GREEN : RED}
              opacity="0.85"
            />
          );
        })}

        <text x="24" y="122" fontSize="9.5" fontWeight="700" fill={GREEN}>приток ↑</text>
        <text x="284" y="122" textAnchor="end" fontSize="9.5" fontWeight="700" fill={RED}>↓ отток</text>
      </svg>
    </Figure>
  );
}

