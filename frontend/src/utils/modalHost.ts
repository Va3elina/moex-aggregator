/**
 * Куда монтировать полноэкранные модалки сайта, чтобы они не оказались ПОД
 * хромом терминала.
 *
 * Проблема: панель песочницы — absolute-блок со своим z-index, то есть
 * СТЕКИНГ-КОНТЕКСТ. Модалка внутри неё (`position: fixed; z-50`) считает свой
 * z-index относительно панели, а у топбара терминала z-index 50 на верхнем
 * уровне — поэтому верх модалки уезжал под топбар и выглядел «обрезанным»
 * (фидбек Вадима: «модалки будто обрезаны сверху»).
 *
 * Решение: рендерить порталом ВНЕ панели. Хост — корень терминала (`.sb-root`
 * или развёрнутая панель `.sb-max`), а не body: на нём висят `data-sbtheme` и
 * `data-theme`, из которых модалка берёт палитру. Порталим в body только когда
 * терминала на странице нет (обычный сайт) — там стекинг-контекст не мешает.
 */
export function modalHost(): HTMLElement {
  if (typeof document === 'undefined') return null as unknown as HTMLElement;
  return (document.querySelector('.sb-max, .sb-root') as HTMLElement | null) ?? document.body;
}

/** z-index модального слоя: выше топбара терминала (50) и его оверлеев (100000). */
export const MODAL_LAYER_Z = 100100;
