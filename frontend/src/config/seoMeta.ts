/**
 * Resolve metadata по pathname с fallback на главную. Поддерживает динамические
 * сегменты: /admin/users/123 → ищем '/admin/users/:userId' через паттерн-match.
 */
export function getSeoMeta(pathname: string): SeoMeta {
    if (SEO_META[pathname]) return SEO_META[pathname]
    // Точные пути не нашли — пробуем сматчить по prefix (для admin/billing динамики)
    for (const key of Object.keys(SEO_META)) {
        if (pathname.startsWith(key) && key !== '/') return SEO_META[key]
    }
    return SEO_META['/']
}
