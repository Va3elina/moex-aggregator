"""Профиль стиля черновика против постов канала — числом, а не мнением.

Сервис для Шага В: писатель проверяет свой текст ДО отправки и видит, куда он уехал
от канала. Ядро вынесено сюда, а не в research/, по практической причине: research/ в
api-образ не копируется, а api/ копируется. CLI в
research/content_pipeline_v2/style_profile.py — тонкая обёртка над этим модулем.

⚠️ Что этот скор НЕ значит. Он измеряет «похоже на канал», а не «хорошо»: в корпусе
нет оценок качества, известно лишь, что канал это опубликовал. Идеально «канальный»
пост может быть скучным или неверным по фактам — за факты отвечает судья.

⚠️ Чем он лучше судьи: детерминирован и бесплатен. Судья — сам LLM, и его вердикт
плавает (01.09: один и тот же текст получил «брак», потом «годится»). Профиль на том
же тексте всегда даёт одно и то же число.

Признаки отобраны замером, а не на глаз. Разделяют канал и черновики четыре:
                        канал   черновики ИИ   после сокращений 01.09
  знаков                  661        881            393
  слов в предложении       11         18              9
  чисел на 100 знаков    0,40       1,13           1,35
  доля предл. с числом   0,29       0,50           0,57
Померены и ОТБРОШЕНЫ как неразделяющие: температура (! + эмодзи) 1,00 против 0,80,
число эмодзи, количество абзацев, предложений в абзаце.

Главное, что нашёл этот замер и не поймало ни одно правило: убирая прозу и оставляя
факты, мы подняли плотность чисел ВТРОЕ выше канала. У канала 661 знак с малым числом
цифр — есть связки и дыхание; у нас 393 знака почти целиком из чисел.
"""
import gzip
import json
import os
import re
import statistics as st
from functools import lru_cache

# ⚠️ Эталон ЖАНРОВЫЙ, и это выяснилось на живом посте. Пост про мандат по фондам
# получил замечание «пост длинный: 1239 знаков против 661» — а 1239 это РОВНО медиана
# жанра «фонды». Замер по срезам:
#                     ОИ (n=45)  фонды (n=17)  весь FRAME (n=82)
#   знаков                 679         1239           843
#   слов в предложении      11           12            11
#   чисел на 100 знаков   0,38         0,43          0,41
#   доля прозы            0,67         0,73          0,71
# Плотность и проза у жанров почти совпадают, а ДЛИНА отличается вдвое. Сравнивать
# пост про фонды с эталоном «ОИ» значит требовать сократить его вдвое без причины.
#
# Рубрика берётся из самого текста — она стоит последней строкой, так что определять
# её отдельным параметром не нужно.
_GENRES = {
    "ои": ("#открытыйинтерес", "#открытыепозиции", "#ОткрытыйИнтерес"),
    "фонды": ("#деньгивфондах", "#cделкифондов", "#сделкифондов",
               "#Потоккапитала", "#ПотокКапитала"),
}
# ⚠️ Порог 15 постов. Ниже него медиана и разброс шумят: у «#сезонность» всего 8
# постов, и эталон по ним увёл бы сильнее, чем общий по каналу.
_MIN_SLICE = 15
GENRE_TAGS = _GENRES["ои"]
# Признаки, которые реально разделяют канал и черновики (см. докстринг модуля).
KEYS = ("знаков", "слов_в_предл", "чисел_на_100зн", "доля_предл_с_числом",
        "доля_прозы")

_CANDIDATE_PATHS = [
    os.environ.get("CORPUS_PATH", ""),
    "/app/data/corpus/corpus.json.gz",
    os.path.join(os.path.dirname(os.path.dirname(os.path.dirname(
        os.path.abspath(__file__)))), "research", "content_pipeline_v2", "dataset",
        "corpus.json.gz"),
]
_EMO = re.compile(r"[\U0001F300-\U0001FAFF☀-➿]")
# Тикеры и коды латиницей: GAZPF, AFKS, IMOEX. Нужны, чтобы отделить настоящую прозу
# от предложений, где вместо слов стоят обозначения.
_TICK = re.compile(r"#?[A-Z]{3,6}\b")


def _paras(text: str) -> list:
    """Абзацы без хэштегов и без подписи канала.

    ⚠️ Подпись @FrameTool снимать ОБЯЗАТЕЛЬНО: у опубликованных постов она идёт
    последней строкой, и без её отсева «последним абзацем» оказывается она — весь
    замер тогда даёт нули (наступал на это 01.09).
    """
    return [x.strip() for x in (text or "").split("\n")
            if x.strip() and not x.strip().startswith("#")
            and "@FrameTool" not in x and len(re.sub(r"[\W_]", "", x)) > 8]


def profile(text: str):
    paras = _paras(text)
    if not paras:
        return None
    body = " ".join(paras)
    sents = [s for p in paras for s in re.split(r"(?<=[.!?])\s+", p)
             if len(s.split()) > 1]
    if not sents:
        return None
    nums = re.findall(r"\d+[,.]?\d*", body)
    return {
        "знаков": len(text),
        "абзацев": len(paras),
        "слов_в_предл": st.median([len(s.split()) for s in sents]),
        "чисел_на_100зн": round(100 * len(nums) / max(len(body), 1), 2),
        "доля_предл_с_числом": round(
            sum(bool(re.search(r"\d", s)) for s in sents) / len(sents), 2),
        # ⚠️ Пятый признак, добавлен 01.09 и объяснил остаток разрыва. Доля
        # предложений БЕЗ чисел И БЕЗ тикеров — та «соединительная ткань», которую мы
        # вырезали: у канала 0,65, у прежних черновиков 0,50, у наших 0,38.
        # Тонкость: доля предложений С ЧИСЛАМИ у нас уже совпадает с каналом
        # (0,30 против 0,29). Значит дело не в числах — вместо прозы у нас стоят
        # ТИКЕРЫ И КОДЫ (GAZPF, AFKS, ruB), и без этого признака перекос не виден.
        "доля_прозы": round(
            sum(1 for s in sents
                if not re.search(r"\d", s) and not _TICK.search(s)) / len(sents), 2),
        "температура": round((text.count("!") + len(_EMO.findall(text)))
                              / len(paras), 2),
    }


def detect_genre(text: str):
    """Жанр по рубрике из самого текста. None — рубрика незнакомая или отсутствует."""
    low = (text or "").lower()
    for name, tags in _GENRES.items():
        if any(t.lower() in low for t in tags):
            return name
    return None


@lru_cache(maxsize=8)
def channel_reference(genre: str | None = None):
    """Медиана и разброс по срезу канала. Читается раз на процесс, кэш по жанру.

    Порядок выбора: жанровый срез → весь канал FRAME → None. Жанровый берём только
    если постов хватает (_MIN_SLICE), иначе эталон сам станет шумом.
    """
    path = next((p for p in _CANDIDATE_PATHS if p and os.path.exists(p)), None)
    if not path:
        return None
    with gzip.open(path, "rt", encoding="utf-8") as f:
        corpus = json.load(f)

    def slice_prof(pred):
        return [p for p in (profile(x.get("text") or "") for x in corpus if pred(x)) if p]

    tags = _GENRES.get(genre or "", ())
    prof, label = [], ""
    if tags:
        prof = slice_prof(lambda x: any(t.lower() in (x.get("text") or "").lower()
                                         for t in tags))
        label = f"жанр «{genre}»"
    if len(prof) < _MIN_SLICE:
        prof = slice_prof(lambda x: (x.get("channel") or "").upper().startswith("FRAME"))
        label = "весь канал"
    if len(prof) < 10:
        return None
    return {"медиана": {k: st.median([x[k] for x in prof]) for k in KEYS},
            "разброс": {k: st.stdev([x[k] for x in prof]) for k in KEYS},
            "n": len(prof), "эталон": label}


_MIXED_TOKEN = re.compile(r"\S*[A-Za-z]\S*[А-Яа-яЁё]\S*|\S*[А-Яа-яЁё]\S*[A-Za-z]\S*")


def technical_warnings(text: str) -> list:
    """Тихие технические дефекты, которые НЕ увидит ни человек, ни модель-судья.

    ⚠️ Живой случай 01.09: черновик написал уровень рейтинга «ruВ» с КИРИЛЛИЧЕСКОЙ
    «В» вместо латинской B. Визуально неотличимо, а значение неверное — и судья
    подтвердил numbers_traceable, потому что глазами уровень совпадал с брифом.
    Такое ловится только кодом, поэтому проверка здесь, а не в рубрике.

    Ищем токены, где латиница и кириллица смешаны внутри одного слова: «ruВ»,
    «AА-(RU)», «GAZРF». Обычные русские слова и обычные тикеры сюда не попадают —
    в них алфавит один.
    """
    out = []
    seen = set()
    for tok in _MIXED_TOKEN.findall(text or ""):
        clean = tok.strip("«»\"'(),.;:!?-—")
        if not clean or clean in seen or len(clean) > 24:
            continue
        # Хэштеги вида #открытыйинтерес и адреса пропускаем: там смешение штатное.
        if clean.startswith("#") or "/" in clean or "@" in clean:
            continue
        seen.add(clean)
        out.append(f"СМЕШАННЫЙ АЛФАВИТ в «{clean}»: латиница и кириллица в одном "
                    f"слове. Проверь по брифу — уровень рейтинга или тикер написан "
                    f"похожей буквой из другого алфавита, и значение стало неверным.")
    return out


def _guidance(dev: dict, prof: dict, ref: dict) -> list:
    """Отклонения → что именно делать. Порядок важен: сначала то, что уехало сильнее.

    ⚠️ Советы говорят про ТЕКСТ, а не про цифру скора. «Плотность +1,4σ» модель
    исправит механически — выкинет число и сломает мысль. «Два предложения из трёх у
    канала без чисел» подсказывает, что делать: добавить связок, а не срезать факты.
    """
    out = []
    # ⚠️ Подсказки СИММЕТРИЧНЫ по каждому признаку. Первая версия ругалась только на
    # длинные предложения и на короткий пост — про рублёные предложения и про лишние
    # числа «снизу» не говорила ничего. Итог: батч дал 7 слов в предложении против 11
    # у канала (−1,49σ), и писатель этого просто не видел. Односторонняя метрика
    # толкает в свою сторону до упора.
    if dev["чисел_на_100зн"] > 0.8 or dev["доля_предл_с_числом"] > 0.8:
        out.append(
            f"ЦИФР СЛИШКОМ МНОГО: {prof['чисел_на_100зн']} на 100 знаков против "
            f"{ref['чисел_на_100зн']:.2f} у канала. У канала два предложения из трёх "
            f"вообще без чисел. Не срезай факты — добавь связок и объяснений между "
            f"ними, чтобы текст дышал.")
    if dev["слов_в_предл"] > 1.0:
        out.append(f"ПРЕДЛОЖЕНИЯ ДЛИННЫЕ: {prof['слов_в_предл']:g} слов против "
                   f"{ref['слов_в_предл']:.0f} у канала. Разбей на короткие, по одному "
                   f"факту в каждом, без вставок в скобках.")
    elif dev["слов_в_предл"] < -0.8:
        out.append(f"ПРЕДЛОЖЕНИЯ РУБЛЕНЫЕ: {prof['слов_в_предл']:g} слов против "
                   f"{ref['слов_в_предл']:.0f} у канала — это уже телеграфный стиль. "
                   f"Соедини пары коротких там, где мысль общая: «Акция упала вдвое. "
                   f"Толпа перешла в лонг» → «Акция упала вдвое, а толпа за это же "
                   f"время перешла в лонг». Целься примерно в "
                   f"{ref['слов_в_предл']:.0f} слов.")
    if dev["знаков"] < -0.8:
        out.append(f"ПОСТ КОРОТКИЙ: {prof['знаков']} знаков против "
                   f"{ref['знаков']:.0f} у канала. Это НЕ повод дописать цифр: если "
                   f"фактуры в брифе мало, короткий пост честнее дотянутого.")
    if dev["знаков"] > 1.0:
        out.append(f"ПОСТ ДЛИННЫЙ: {prof['знаков']} знаков против "
                   f"{ref['знаков']:.0f} у канала. Убери самый слабый абзац целиком.")
    if dev["доля_прозы"] < -0.8:
        out.append(
            f"МАЛО ПРОЗЫ: {prof['доля_прозы']:.2f} предложений без чисел и без тикеров "
            f"против {ref['доля_прозы']:.2f} у канала. У канала две трети предложений — "
            f"обычные слова; у нас вместо них обозначения вроде GAZPF и A+(RU). "
            f"Добавь предложения, объясняющие смысл, где нет ни цифры, ни тикера.")
    # ⚠️ Порог АБСОЛЮТНЫЙ, а не в сигмах. Живой случай 01.09: писатель выпустил
    # черновик, где не осталось НИ ОДНОЙ цифры — пропали «₽320 млрд» и «28 августа»,
    # вместо них «привлекла деньги» и «в конце августа». Сигма это не поймала: у
    # канала медиана 0,40 при разбросе 0,46, поэтому ноль чисел даёт лишь −0,87σ.
    # Широкий разброс эталона делает сигму слепой у нуля — там нужен пол по существу.
    if prof["чисел_на_100зн"] < 0.15 or (dev["чисел_на_100зн"] < -1.0
                                         and dev["доля_предл_с_числом"] < -1.0):
        сколько = ("в тексте НЕТ НИ ОДНОГО ЧИСЛА" if prof["чисел_на_100зн"] == 0
                    else f"{prof['чисел_на_100зн']:.2f} числа на 100 знаков")
        out.append(f"ЦИФР СЛИШКОМ МАЛО: {сколько} против "
                   f"{ref['чисел_на_100зн']:.2f} у канала. Пост про рынок без чисел "
                   f"не отличается от чужого мнения. Верни главное число из брифа и "
                   f"конкретные даты: «привлекла деньги» вместо «привлекла ₽320 млрд» "
                   f"и «в конце августа» вместо «28 августа» — это потеря фактуры, а "
                   f"не экономия цифр.")
    return out


def score(text: str):
    ref = channel_reference(detect_genre(text))
    prof = profile(text)
    if not ref or not prof:
        return None
    dev = {k: round((prof[k] - ref["медиана"][k]) / ref["разброс"][k], 2)
           for k in KEYS}
    return {
        "профиль": prof,
        "эталон_канала": ref["медиана"],
        "отклонение_сигм": dev,
        "среднее_отклонение": round(
            st.mean(abs(v) for v in dev.values()), 2),
        "что_поправить": _guidance(dev, prof, ref["медиана"]),
        # Технические предупреждения отдельно от стилевых советов: это не «похоже на
        # канал», а прямая ошибка в тексте.
        "предупреждения": technical_warnings(text),
        "пояснение": ("Это похожесть на канал, НЕ качество: в корпусе нет оценок "
                       "качества. За факты отвечает судья."),
        "n_эталона": ref["n"],
        "срез_эталона": ref.get("эталон", ""),
    }
