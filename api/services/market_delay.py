"""
Задержка биржевых данных по лицензии MOEX.

Условие контракта: ЦЕНА (свечи) раздаётся не раньше чем через 15 минут после
торгов. Открытый интерес (FUTOI) под это ограничение не подпадает и остаётся
актуальным — решение владельца 2026-08-10: «задержка только цены, ОИ показываем
как есть, чтобы его не терять».

Отсюда несимметричная картина на графике: точки ОИ есть до текущей минуты, а
свечей на этом отрезке ещё нет. Пустой хвост читался бы как «торгов не было»,
поэтому цену на нём РАСТЯГИВАЕМ — продлеваем последнее известное значение с
пометкой stretched. Когда настоящая свеча приходит, растянутая точка на том же
времени заменяется фактической (см. chart_live.append_stretched_price).

⚠️ ВРЕМЯ. Контейнер живёт в UTC (tzname = ('UTC','UTC')), а в БД лежит НАИВНОЕ
московское: на 2026-08-10 20:34 UTC последняя 5-минутка была 23:30. Наивный
datetime.now() отрезал бы три часа торгов, поэтому потолок считаем в МСК и
возвращаем НАИВНЫМ — в том же виде, в каком времена лежат в базе.
"""
from datetime import datetime, timedelta, timezone

# Сколько минут держим цену. Значение из контракта с MOEX; менять только вместе
# с условиями лицензии.
PRICE_DELAY_MINUTES = 15

_MSK = timezone(timedelta(hours=3))


def now_msk() -> datetime:
    """Текущее московское время, НАИВНОЕ — как времена в БД."""
    return datetime.now(_MSK).replace(tzinfo=None)


def price_cutoff() -> datetime:
    """Момент лицензии: сделок позже этого мгновения раздавать нельзя.

    ⚠️ Это НЕ потолок для begin_time — фильтровать бары напрямую по нему
    нельзя, см. cutoff_for_interval. Наружу отдавайте только результат
    cutoff_for_interval, иначе задержка окажется короче договорной.
    """
    return now_msk() - timedelta(minutes=PRICE_DELAY_MINUTES)


# Таймфреймы под задержкой. Только 5 минут — решение владельца 2026-08-11:
# «задержка касается только интрадей 5-минуток».
#
# Часовая и дневная свеча приходят раз в час и раз в день, то есть по своей
# природе не поток реального времени, и придерживать их незачем. А вот всё, что
# ЧЕРПАЕТ из 5-минуток, под задержку попадает, даже если показывается на другом
# таймфрейме: live-точка дневного графика (chart_live) и цена акции на карте
# рынка (intraday_close в mv_heatmap_stocks) — это ровно 5-минутные данные.
DELAYED_INTERVALS = (5,)


def cutoff_for_interval(interval: int | None) -> datetime | None:
    """Потолок для `begin_time`, либо None — если ТФ не под задержкой.

    None означает «фильтровать не надо»: вызывающий обязан это учесть и не
    подставлять его в SQL как границу (сравнение с NULL отсекло бы ВСЁ).

    ⚠️ ВЫЧИТАЕМ ДЛИНУ БАРА. Бар помечен НАЧАЛОМ, а покрывает [begin, begin+ТФ):
    у пятиминутки begin_time=14:20 в БД стоит end_time=14:25, то есть внутри
    неё лежит сделка 14:25. Потолок «begin_time <= now-15мин» выпускал такой
    бар в 14:35 — сделку 14:25 через ДЕСЯТЬ минут вместо пятнадцати, и так
    систематически на любом баре (найдено замером 31.08.2026: возраст самой
    свежей видимой сделки 11.1 мин при договорных 15).

    Считаем от КОНЦА бара: begin + ТФ <= now - 15мин, то есть
    begin <= now - 15мин - ТФ. Для 5-минутки это now - 20 минут.
    """
    if interval not in DELAYED_INTERVALS:
        return None
    return price_cutoff() - timedelta(minutes=interval)
