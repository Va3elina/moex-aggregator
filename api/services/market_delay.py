"""
Задержка биржевых данных по лицензии MOEX.

Условие контракта: ЦЕНА (свечи) раздаётся не раньше чем через 15 минут после
торгов. Открытый интерес (FUTOI) под это ограничение не подпадает и остаётся
актуальным — решение владельца 2026-08-10: «задержка только цены, ОИ показываем
как есть, чтобы его не терять».

Отсюда несимметричная картина на графике: точки ОИ есть до текущей минуты, а
свечей на этом отрезке ещё нет. Пустой хвост читался бы как «торгов не было»,
поэтому цену на нём РАСТЯГИВАЕМ — продлеваем последнее известное значение с
пометкой stretched. Когда настоящая свеча приходит, растянутая точка на том же
времени заменяется фактической (см. chart_live.append_stretched_price).

⚠️ ВРЕМЯ. Контейнер живёт в UTC (tzname = ('UTC','UTC')), а в БД лежит НАИВНОЕ
московское: на 2026-08-10 20:34 UTC последняя 5-минутка была 23:30. Наивный
datetime.now() отрезал бы три часа торгов, поэтому потолок считаем в МСК и
возвращаем НАИВНЫМ — в том же виде, в каком времена лежат в базе.
"""
from datetime import datetime, timedelta, timezone

# Сколько минут держим цену. Значение из контракта с MOEX; менять только вместе
# с условиями лицензии.
PRICE_DELAY_MINUTES = 15

_MSK = timezone(timedelta(hours=3))


def now_msk() -> datetime:
    """Текущее московское время, НАИВНОЕ — как времена в БД."""
    return datetime.now(_MSK).replace(tzinfo=None)


def price_cutoff() -> datetime:
    """Потолок свежести ЦЕНЫ: свечи новее этого момента раздавать нельзя."""
    return now_msk() - timedelta(minutes=PRICE_DELAY_MINUTES)
