"""Технические события реорганизации фондов (слияния, частичные ликвидации) — одна таблица
для графика «Деньги в фондах» (api/routers/funds.py) и движка находок (signals/insights).

СЧА фонда в эти дни скачет не от денег инвесторов, а от присоединения активов другого фонда
или частичной ликвидации. Движок находок считал потоки без этой таблицы и видел «отток 1,5 млрд
из фондов золота 03.09.2024» (ликвидация части SBGD) — а настоящий рекорд месячного оттока в
сентябре 2026 (−0,7 млрд) не заметил (правка Вадима к связке #2084, 14.09.2026).

Знак impact_bln: + технический приток (слияние), − технический отток (ликвидация). Значения и даты
взяты из ранее размеченных аннотаций.
"""
FLOW_REORG_CORRECTIONS: dict = {
    "stocks": [
        ("OPIF-432", "2014-12-15", 0.9),
        ("OPIF-43", "2019-09-25", 1.6),
        ("OPIF-1003", "2025-06-06", 3.3),
        ("OPIF-43", "2026-04-17", 2.4),
    ],
    "gold": [
        ("SBGD", "2024-09-03", -1.5),
    ],
    "bonds": [
        ("OPIF-33", "2020-10-22", 7.2),
        ("OPIF-47", "2022-09-15", 4.6),
    ],
}


def correct_flows(fd):
    """Поправка потоков по фондам «как будто события не было» — так же, как на графике сайта:
    день скачка — наибольший |flow| фонда в окне ±10 дней от даты события (устойчиво к лагу
    раскрытия и нерабочим дням), из него вычитается impact. fd — DataFrame с колонками
    ticker, trade_date, flow (рубли); меняется на месте и возвращается."""
    import pandas as pd
    for events in FLOW_REORG_CORRECTIONS.values():
        for ticker, day, impact_bln in events:
            d = pd.Timestamp(day)
            m = (fd["ticker"] == ticker) & ((fd["trade_date"] - d).abs() <= pd.Timedelta(days=10)) & fd["flow"].notna()
            if m.any():
                j = fd.loc[m, "flow"].abs().idxmax()
                fd.loc[j, "flow"] -= impact_bln * 1e9
    return fd
