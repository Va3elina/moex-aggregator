-- Канал обратной связи от человека к системе (исследование 2026-08-31,
-- research/content_pipeline_v2/RESEARCH_2026-08-31.md §2).
--
-- ПРОБЛЕМА. У конвейера постов не было ни одного способа вернуть человеческое
-- суждение в систему:
--   1. signals/content_review_bot.py:_UPDATE_DRAFT и
--      api/routers/content_news.py (edit-эндпоинт) ПЕРЕЗАПИСЫВАЛИ draft_text
--      правкой человека — оригинал ИИ уничтожался безвозвратно. Диффа
--      «что именно правил редактор» не существовало;
--   2. причина отказа не писалась НИКУДА — reviewer_action принимает только
--      'approved'/'rejected'.
-- Следствие: единственным каналом человеческого суждения был Вадим,
-- дописывающий очередное правило в промпт Шага В после каждого плохого поста.
-- Именно поэтому промпт Шага В превратился в журнал багов с датами поимки и
-- дорос до ~13 тыс. знаков (деградация ризонинга у LLM измеряется начиная
-- примерно с 3 тыс. токенов). Промпт выполнял работу, которую должен
-- выполнять датасет.
--
-- Цифры, на которых это видно: за всю жизнь конвейера 932 кандидата → 23
-- черновика → 5 published / 9 rejected / 9 неотревьюенных. 64% решённых
-- черновиков — брак, и ни одна причина брака не сохранена машиночитаемо.
--
-- ЧТО ДЕЛАЕМ. Три колонки, которые превращают каждое ревью в размеченный
-- пример вместо разового решения:
--   draft_text_ai        — оригинал ИИ. Пишется Шагом В одновременно с
--                          draft_text и НИКОГДА не перезаписывается правкой
--                          человека. Пара (draft_text_ai, draft_text) и есть
--                          обучающий сигнал: дифф = что редактор счёл нужным
--                          исправить (edit-based feedback).
--   reviewer_reason      — свободный текст: почему отклонил / что правил.
--   reviewer_reason_code — код из фиксированного списка (signals/config.py:
--                          REVIEW_REASON_CODES) для агрегации. Без кода
--                          свободный текст не сгруппировать, без свободного
--                          текста код теряет детали — нужны оба.
ALTER TABLE content_candidates ADD COLUMN IF NOT EXISTS draft_text_ai TEXT;
ALTER TABLE content_candidates ADD COLUMN IF NOT EXISTS reviewer_reason TEXT;
ALTER TABLE content_candidates ADD COLUMN IF NOT EXISTS reviewer_reason_code VARCHAR(32);

COMMENT ON COLUMN content_candidates.draft_text_ai IS
  'Оригинальный черновик ИИ (Шаг В). Не перезаписывается правкой человека — '
  'дифф с draft_text используется как обучающий сигнал. NULL у строк до миграции 054, '
  'по которым уже было решение человека (текст мог быть отредактирован, различить нельзя).';

-- ЗАДНИМ ЧИСЛОМ, но ТОЛЬКО там, где человек заведомо не трогал текст:
-- reviewer_action IS NULL = карточка ни разу не отревьюена, значит draft_text
-- — чистый вывод ИИ. Это 9 черновиков в статусе draft_ready.
--
-- ⚠️ У 14 РЕШЁННЫХ строк (5 published + 9 rejected) draft_text_ai намеренно
-- остаётся NULL. Причина: кнопка «✏️ Править» в review-боте перезаписывала
-- draft_text, а признака «правили или нет» не сохранялось — скопировать туда
-- draft_text значило бы соврать, назвав возможную правку человека выводом ИИ.
-- (Kanban /admin/content-news тут ни при чём: он показывает черновик только
-- для чтения, эндпоинта правки текста у него нет — проверено. Но карточку в
-- боте получили 22 из 23 черновиков, так что «правку исключить» нельзя почти
-- нигде.)
-- Для eval-набора Фазы 2 это существенная оговорка: 5 опубликованных постов
-- НЕЛЬЗЯ считать чистыми положительными примерами работы ИИ.
UPDATE content_candidates
SET draft_text_ai = draft_text
WHERE draft_text IS NOT NULL
  AND draft_text_ai IS NULL
  AND reviewer_action IS NULL;
