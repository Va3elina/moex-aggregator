-- Версия контракта брифа. Судья (Шаг Г) должен судить черновик ТОЛЬКО по той версии
-- брифа, по которой он написан.
--
-- ЗАЧЕМ. Первые два прогона Шага Г выстрелили по 19 кандидатам, из которых
-- осмысленными были 2. Причина в обоих случаях одна: судья судил СТАРЫЕ черновики
-- по НОВОМУ брифу. Старые брались из полей, которых в брифе v2 больше нет
-- (market_rank, recent_signals, ATR-множитель, двухлетний диапазон oi_context), и
-- честно валились на воротах «каждое число трассируется в бриф». Сужение выборки
-- до status='draft_ready' проблему не решило: среди них 7 из 9 тоже были старыми.
--
-- Признак «уже решён» и признак «написан по актуальному контракту» — РАЗНЫЕ вещи,
-- и вторую нельзя вывести из статуса, дат или наличия черновика. Нужна явная метка.
--
-- 1 = бриф v1 (ATR-множитель, market_rank, recent_signals, oi_context строкой).
-- 2 = бриф v2 (JSON, ГЛАВНОЕ_ЧИСЛО, рамка_сюжета, числа человеческой фразой).
-- Всё, что существовало до этой миграции, — это v1 по определению.
ALTER TABLE content_candidates
    ADD COLUMN IF NOT EXISTS brief_version SMALLINT NOT NULL DEFAULT 1;

COMMENT ON COLUMN content_candidates.brief_version IS
  'Версия контракта брифа, по которому написан draft_text. Судья берёт только '
  'актуальную версию: черновик, написанный по прежнему контракту, обязательно '
  'провалится на воротах фактуры, и это будет артефакт, а не дефект.';

-- Два черновика, уже написанных новым Шагом В в живом прогоне 31.08.
UPDATE content_candidates SET brief_version = 2 WHERE id IN (1104, 1357);

-- Артефактные вердикты по всему, что судилось не по своей версии брифа, — снять.
-- Оставить их значило бы засорить историю ложными «брак» и сбить будущую сверку
-- судьи с реальными решениями человека.
UPDATE content_candidates
SET judge_items = NULL, judge_verdict = NULL, judge_failed = NULL,
    judge_defects = NULL, judge_note = NULL, judge_checked_at = NULL,
    judge_dispatch_attempts = 0
WHERE judge_verdict IS NOT NULL AND brief_version <> 2;
