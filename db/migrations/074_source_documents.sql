-- Слой сырья: то, что забрали из внешнего источника, до всякого разбора.
--
-- ЗАЧЕМ. Каждый фетчер ходил за своими данными сам, и пока источник один — это
-- незаметно. Замер 04.09.2026: страница акционеров smart-lab качалась ДВАЖДЫ в
-- неделю (обход карточек в 04:00 и граф владения в 06:00) — 118 лишних запросов к
-- источнику, от которого мы бережёмся. Никто про дубль не знал: оба скрипта работали
-- правильно.
--
-- Здесь лежит сырое, а разборщики читают отсюда, а не из сети. Забрали один раз —
-- разобрали сколько нужно. Поменялась логика разбора — перезапустили разборщик по
-- сохранённому, не трогая источник.
--
-- ⚠️ ЭТО НЕ «ВСЁ ПОДРЯД». Сюда идёт то, что забрано ИЗ СЕТИ и нужно больше чем
-- одному потребителю: ответы FinanceMarker, RSS ЦБ, пресс-релизы Мосбиржи. Свечи и
-- открытый интерес сюда НЕ идут — они уже структурированы и у них один потребитель.
--
-- ⚠️ ДЕДУП ПО СОДЕРЖИМОМУ, А НЕ ПО ВРЕМЕНИ. Замер: страница smart-lab весит 87 КБ,
-- в gzip 17 КБ. Хранить каждый обход — 0,6 ГБ в год; хранить только изменившееся —
-- 31 МБ. Разница в двадцать раз, и она же даёт побочную пользу: видно, что у
-- эмитента реально поменялось с прошлой недели, на уровне страницы, а не значений.
--
-- ⚠️ ТЕЛО ЖИВЁТ ОГРАНИЧЕННО, МЕТАДАННЫЕ ВЕЧНО. Через 90 дней body обнуляется, а
-- хэш, время и статус остаются: «что и когда менялось» — история, «чем именно оно
-- было» — рабочий материал.
--
-- Применение на проде:
--   docker cp db/migrations/074_source_documents.sql frame-db-1:/tmp/
--   docker exec frame-db-1 psql -U postgres -d moex_db -f /tmp/074_source_documents.sql

CREATE TABLE IF NOT EXISTS source_documents (
    id           BIGSERIAL PRIMARY KEY,
    source       VARCHAR(32)  NOT NULL,   -- financemarker | moex | cbr | smartlab
    -- Что именно забирали: для API — логический ключ («stocks/MOEX:SBER»), для
    -- страницы — URL. Логический ключ, а не URL, потому что у API один адрес с
    -- разными параметрами — по URL они не различались бы человеком.
    doc_key      VARCHAR(300) NOT NULL,
    url          TEXT         NOT NULL,
    http_status  SMALLINT,
    content_type VARCHAR(80),
    -- sha256 тела. Совпал — значит источник ничего не поменял, новой строки нет.
    content_hash CHAR(64)     NOT NULL,
    body         BYTEA,                   -- gzip; обнуляется по ретеншену
    body_bytes   INTEGER,                 -- размер ДО сжатия, чтобы считать объёмы
    first_seen   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    last_seen    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    -- Когда разобрали. NULL = лежит сырым и ждёт разборщика; это же признак
    -- «перезапустить разбор» после смены логики: обнулил колонку — и всё поедет заново.
    parsed_at    TIMESTAMPTZ,
    parse_note   TEXT
);

-- Одна строка на (что забирали, каким оно было). Повторный забор неизменного
-- двигает last_seen, а не плодит версии — тот же приём, что SCD-2 у метрик.
CREATE UNIQUE INDEX IF NOT EXISTS uq_source_documents
    ON source_documents (source, doc_key, content_hash);
-- «Что нового не разобрано» — главный запрос разборщиков.
CREATE INDEX IF NOT EXISTS idx_source_documents_unparsed
    ON source_documents (source, parsed_at NULLS FIRST, last_seen DESC);
-- «Что менялось у этого объекта» — история по ключу.
CREATE INDEX IF NOT EXISTS idx_source_documents_key
    ON source_documents (doc_key, last_seen DESC);

COMMENT ON COLUMN source_documents.content_hash IS
  'sha256 тела. Совпадение = источник ничего не менял: пишем last_seen, новой строки '
  'не создаём. Отсюда 31 МБ в год вместо 0,6 ГБ.';
COMMENT ON COLUMN source_documents.parsed_at IS
  'NULL = ждёт разбора. Обнуление колонки = команда перезапустить разбор по уже '
  'сохранённому сырью, без единого запроса в сеть.';
