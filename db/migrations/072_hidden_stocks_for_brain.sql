-- Одиннадцать компаний в ингест, но НЕ на сайт.
--
-- ЗАЧЕМ. Детектор сигналов смены владения нашёл события по компаниям, которых нет ни
-- в справочнике, ни в instruments: МГКЛ, ТГК-2, ИВА, ЭЛ5-Энерго, Россети Юг и другие.
-- Про них пишут, они торгуются на TQBR, но для нас их не существует — а значит второй
-- мозг не может ни резолвить их в новостях, ни показать по ним карточку.
--
-- ⚠️ НА САЙТЕ ОНИ ПОЯВИТЬСЯ НЕ ДОЛЖНЫ. Требование Вадима прямое: список бумаг в
-- модалке ОИ и в каталоге остаётся прежним. Поэтому hidden = true, и это работает
-- ровно так, как нужно, потому что фильтруют по нему РАЗНЫЕ слои по-разному:
--   • api/routers/instruments.py (каталог и пикер, он же модалка) — фильтрует
--     «NOT i.hidden», значит новые бумаги туда НЕ попадут;
--   • Candles/fetch_candles_spot_realtime.py (ингест свечей) — hidden НЕ смотрит,
--     значит котировки качаться будут.
-- Механизм не новый: колонка заведена как «убрать, но не удалить» для делистнутых
-- бумаг, у которых данные сохраняются. Здесь тот же приём в обратную сторону —
-- «добавить, но не показать».
--
-- ⚠️ ОСТАЁТСЯ ОДНА ЩЕЛЬ, СОЗНАТЕЛЬНО НЕ ЗАКРЫТАЯ ЗДЕСЬ. Публичный API
-- (api/routers/public_api.py, GET /instruments) по hidden НЕ фильтрует — сейчас он
-- отдаёт в том числе 11 делистнутых фьючерсов, которые каталог уже прячет. Добавить
-- туда фильтр — однострочная правка, но она изменит выдачу платного эндпоинта, а
-- менять поведение сайта без спроса нельзя. Вопрос вынесен Вадиму отдельно.
--
-- Данные сверены с ISS MOEX 03.09.2026: все одиннадцать торгуются на TQBR, имена и
-- ISIN официальные. Ещё две компании из находок детектора НЕ добавлены, потому что
-- на бирже не торгуются: OPIN (ИНГРАД) и OMZZ (ОМЗ) — свечей по ним всё равно не
-- будет, а справочник заполнился бы тикерами-призраками.
