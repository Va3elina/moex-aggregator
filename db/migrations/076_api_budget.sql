-- 076: свой счётчик расхода платного API.
--
-- Зачем. 04.09.2026 месячная квота FinanceMarker (400) была выбрана в ноль и ушла
-- в −3, а фетчер этого не заметил: он спрашивал у самого источника поле
-- token_info.day_limit, печатал его как «остаток запросов» и получал 388 в момент,
-- когда пул уже был пуст. Число существовало, обновлялось и выглядело правдоподобно,
-- но измеряло не то, что списывается. Плюс внутренний счётчик жил в объекте клиента
-- и обнулялся при каждом запуске — три прогона подряд каждый считал с нуля.
--
-- Отсюда правило: предохранитель считает САМ и НА ДИСКЕ. Поле источника остаётся
-- только справочной строкой в логе.
--
-- Цена запроса не равна единице: 145 вызовов компаний списали ~403 единицы
-- (≈2.8 на вызов с include из 8 разделов). Точное правило биллинга неизвестно, а
-- выяснять его можно только новыми запросами, поэтому цена задаётся коэффициентом
-- и по умолчанию округлена ВВЕРХ — упереться в потолок рано дешевле, чем поздно.

CREATE TABLE IF NOT EXISTS api_budget (
    source       VARCHAR(32)  NOT NULL,
    period_month DATE         NOT NULL,   -- первое число месяца квоты
    spent        NUMERIC(10,2) NOT NULL DEFAULT 0,
    limit_total  INTEGER      NOT NULL,
    calls        INTEGER      NOT NULL DEFAULT 0,  -- сырое число вызовов, для сверки цены
    updated_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    PRIMARY KEY (source, period_month)
);

COMMENT ON COLUMN api_budget.spent IS 'списано по нашей оценке (calls × цена), не по данным источника';
COMMENT ON COLUMN api_budget.calls IS 'фактических HTTP-вызовов; spent/calls = фактическая цена, сверять с панелью источника';

