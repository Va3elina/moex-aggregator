-- 097: автовакуум по вставкам для candles и open_interest — чтобы покрывающие
-- индексы (миграция 047) действительно работали как Index Only Scan.
--
-- ПРОБЛЕМА (замер на проде 2026-09-15). Линия цены в «Сделках фондов» у
-- пользователя грузилась 1-9 с на бумагу, у админа мгновенно. Публичная
-- версия цены (session_close.secid_closes) читает пятиминутки за 60 дней.
-- План идеальный — Index Only Scan по покрывающему индексу — но:
--
--   Index Only Scan using idx_candles_intraday_cover ... rows=7398
--     Heap Fetches: 18798
--     Buffers: shared hit=10551 read=1717
--     I/O Timings: shared read=3432.998      ← 3.5 с ввода-вывода
--
-- Index Only Scan берёт строку из индекса только если страница таблицы
-- помечена в карте видимости как «все строки видимы». Бит ставит только
-- VACUUM. candles и open_interest — insert-only таблицы (ингест дописывает
-- бары каждые 5 минут, ничего не удаляет), и обычный автовакуум по мёртвым
-- строкам до них не доходит: мёртвых строк нет. Порог вакуума по вставкам
-- (PG13+) по умолчанию 1000 + 20% таблицы = ~5 млн строк для candles, то
-- есть раз в несколько месяцев. Всё, что вставлено с тех пор — а это ровно
-- «последние недели», которые читают цена 19:00, графики ОИ 5м/1ч и
-- теплокарта — читается через таблицу, случайными страницами с диска.
-- Ровно об этом предупреждала 047 («ОБЯЗАТЕЛЕН VACUUM»), но разово.
--
-- РЕШЕНИЕ. Порог по вставкам для этих двух таблиц — фиксированные 20 000
-- строк вместо процента от таблицы. Дневной поток ~60 тыс. строк в candles
-- (акции 5м ~19 тыс., фьючерсы 5м ~40 тыс.), то есть автовакуум будет
-- проходить несколько раз в день. Он инкрементальный: страницы с уже
-- выставленным битом пропускает по карте видимости, так что каждый проход
-- трогает только свежие страницы и стоит секунды, а не минуты.
--
-- Плюс разовый VACUUM (ANALYZE) сейчас — выставить биты по всей истории.
-- На 11 ГБ это минуты (см. 047), таблицы не блокирует, можно на живом проде.
--
-- Применение (вне транзакции, VACUUM её не терпит):
--   cat db/migrations/097_candles_oi_autovacuum_insert.sql | docker exec -i frame-db-1 psql -U postgres -d moex_db
--
-- Проверка после: в pg_stat_user_tables у candles растёт autovacuum_count и
-- n_ins_since_vacuum держится ниже порога; EXPLAIN (ANALYZE, BUFFERS) запроса
-- secid_closes показывает Heap Fetches: 0.

ALTER TABLE candles SET (
    autovacuum_vacuum_insert_threshold = 20000,
    autovacuum_vacuum_insert_scale_factor = 0.0
);

ALTER TABLE open_interest SET (
    autovacuum_vacuum_insert_threshold = 20000,
    autovacuum_vacuum_insert_scale_factor = 0.0
);

VACUUM (ANALYZE) candles;

VACUUM (ANALYZE) open_interest;
