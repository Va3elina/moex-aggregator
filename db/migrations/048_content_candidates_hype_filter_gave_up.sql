-- Терминальное состояние для give-up Шага Н (найдено 2026-08-11).
--
-- Баг: _GIVE_UP_HYPE_FILTER писал ТОЛЬКО hype_filter_checked_at = now(), не
-- меняя ничего, что выводит строку из выборки «сдались». Условия отбора
-- (hype_filter_result IS NULL + attempts >= MAX) остаются истинными навсегда,
-- а hype_filter_checked_at < cutoff снова становится истинным ровно через
-- DISPATCH_COOLDOWN_MIN (15 мин) — столько же, сколько период крона. Итог:
-- один и тот же алерт «Шаг Н сдался по N кандидатам» уходил Вадиму каждые
-- полчаса бесконечно (живой случай: 15 кандидатов, 13 повторов за 6 часов).
--
-- У Шага А/В такого нет: их give-up пишет терминальный status (discarded /
-- pending), и строка физически выпадает из выборки. У Шага Н статуса нет —
-- это побочный канал для бота коллеги, он намеренно не трогает status
-- кандидата, поэтому ему нужен собственный признак «сдались».
--
-- Почему отдельная колонка, а не hype_filter_result = FALSE: результат —
-- BOOLEAN с семантикой ответа модели (FALSE = «это шум/не новость»), и он
-- управляет уведомлением коллеги. Записать туда FALSE при отсутствии вердикта
-- значило бы соврать: «модель решила, что это мусор», хотя она не отвечала.
ALTER TABLE content_candidates ADD COLUMN IF NOT EXISTS hype_filter_gave_up_at TIMESTAMPTZ;

-- Разовое гашение уже зависших: у кого попытки исчерпаны, а вердикта так и
-- нет — помечаем сдавшимися задним числом, иначе новый код выдаст по ним ещё
-- один (последний) алерт о том, о чём уже отчитался 13 раз.
UPDATE content_candidates
SET hype_filter_gave_up_at = now()
WHERE hype_filter_result IS NULL
  AND source_url IS NOT NULL
  AND hype_filter_dispatch_attempts >= 3
  AND hype_filter_gave_up_at IS NULL;
