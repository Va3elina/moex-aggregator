-- Точность разметки по имени: проверка выборки из 40 новостей показала ~40 %
-- верных срабатываний. Три системные причины и их лекарства:
--   1) «Россети» → две компании, «Ренессанс»/«МосБиржа» из имён активов фондов —
--      правила, общие для нескольких компаний или однословные из fund_asset_name,
--      помечаются неоднозначными автоматически (пересев обновляет флаг, пока
--      правило не тронуто руками — manual);
--   2) «Индекс Мосбиржи» ≠ компания MOEX — у правила есть exclude_regex (что вычесть
--      из текста) и verify_regex (что должно остаться);
--   3) дайджесты «Итоги дня» и «Доброе утро! ожидаем события» упоминают по 5–15
--      компаний — по имени их не размечаем.
ALTER TABLE brain_name_rules
    ADD COLUMN IF NOT EXISTS exclude_regex TEXT,      -- вычесть из текста перед проверкой (напр. «индекс мосбиржи»)
    ADD COLUMN IF NOT EXISTS verify_regex  TEXT,      -- что должно остаться после вычитания (напр. «мосбирж»)
    ADD COLUMN IF NOT EXISTS manual        BOOLEAN NOT NULL DEFAULT FALSE;  -- правил руками: пересев не трогает флаги
