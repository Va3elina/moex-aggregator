-- 079: отметка НАЧАЛА прогона — чтобы было видно, что идёт прямо сейчас.
--
-- pipeline_runs до сих пор писался ТОЛЬКО по завершении, поэтому «что работает
-- в эту минуту» узнать было неоткуда: снимок показывал прошлое, а идущий процесс
-- выглядел точно так же, как не запускавшийся. Для приборной панели это и есть
-- главный вопрос — «данные капают или встали».
--
-- ⚠️ ОТДЕЛЬНАЯ КОЛОНКА, А НЕ СТАТУС 'running'. Статусом это кодировать нельзя:
-- убитый по дороге процесс навсегда остался бы «работающим», и вычистить его было
-- бы некому. started_at такого не создаёт — «идёт сейчас» это ПРОИЗВОДНОЕ
-- (started_at > last_run_at), а зависший прогон сам себя выдаёт возрастом started_at.

ALTER TABLE pipeline_runs ADD COLUMN IF NOT EXISTS started_at TIMESTAMPTZ;

COMMENT ON COLUMN pipeline_runs.started_at IS
  'начало последнего прогона; идёт сейчас = started_at > last_run_at';
