-- Сигналы смены владения: кандидаты в рёбра графа, найденные в архиве новостей.
--
-- ЗАЧЕМ. Граф владения курируемый, и это верно: цена ложного ребра высока — агент
-- начнёт объяснять движение одной бумаги событиями чужой компании, и объяснит
-- уверенно. Но курируемый не значит «искать вручную». Автомат ПРЕДЛАГАЕТ, человек
-- УТВЕРЖДАЕТ; эта таблица — очередь предложений.
--
-- ⚠️ ЗДЕСЬ НЕ ФАКТЫ, А ПОВОДЫ ПОСМОТРЕТЬ. Ничто отсюда не попадает в world_facts
-- автоматически, ни при каком уровне уверенности. Проба автодобычи рёбер по тексту
-- новостей уже давала мусор: дочерняя компания почти никогда не названа тикером
-- («дочерней компании Новатэка», «ООО Башенная»).
--
-- Замер на проде 03.09.2026 по архиву в 487 тыс. сообщений:
--   строгий фильтр (формулировки 714-П)  — 174 сообщения всего, 91 за полгода;
--   широкий (доля/пакет + продал/купил)  — 1 564 всего, 133 за полгода, из них
--                                          63 несут процент в тексте.
-- Это примерно ОДИН сигнал в день — очередь, которую человек реально разберёт.
-- Распределение по компаниям ровное (ASTR 20, WUSH 18, MGNT 15), 156 из 174
-- текстов уникальны: спама одного эмитента нет.
--
-- Применение на проде:
--   docker cp db/migrations/071_ownership_signals.sql frame-db-1:/tmp/
--   docker exec frame-db-1 psql -U postgres -d moex_db -f /tmp/071_ownership_signals.sql

CREATE TABLE IF NOT EXISTS ownership_signals (
    id           BIGSERIAL PRIMARY KEY,
    -- Ссылка на первоисточник в архиве. Пара (channel, message_id) — первичный ключ
    -- news_archive, поэтому дважды один и тот же пост в очередь не попадёт даже при
    -- перекрывающихся окнах сканирования.
    channel      VARCHAR(120) NOT NULL,
    message_id   BIGINT       NOT NULL,
    posted_at    TIMESTAMPTZ  NOT NULL,
    tickers      TEXT[]       NOT NULL DEFAULT '{}',
    snippet      TEXT         NOT NULL,
    -- строгий — формулировки существенного факта по 714-П («право распоряжаться»,
    --           «голосующих акций»): почти всегда настоящее раскрытие;
    -- широкий  — доля/пакет/акционер рядом с продал/купил/залог: и события, и planы,
    --            и слухи. Полезен, но требует чтения.
    strength     VARCHAR(12)  NOT NULL,
    -- Процент в тексте — сильный признак конкретики: «сократил с 0,3625% до 0,3409%»
    -- против «планирует продать госдолю».
    has_percent  BOOLEAN      NOT NULL DEFAULT FALSE,
    -- есть_ребро — у компании уже есть связь в графе: значит сигнал скорее об
    --              ИЗМЕНЕНИИ доли;
    -- нет_ребра  — возможно, новая связь, которой мы не знаем.
    edge_state   VARCHAR(12)  NOT NULL DEFAULT 'нет_ребра',
    -- новый | подтверждён | отклонён. Подтверждение НЕ создаёт ребро само:
    -- оно означает «я посмотрел, ребро завёл (или обновил) руками».
    status       VARCHAR(16)  NOT NULL DEFAULT 'новый',
    reviewed_at  TIMESTAMPTZ,
    review_note  TEXT,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    UNIQUE (channel, message_id)
);

-- Главный запрос очереди: «что новое, сильное — сверху».
CREATE INDEX IF NOT EXISTS idx_ownership_signals_queue
    ON ownership_signals (status, strength, posted_at DESC);
CREATE INDEX IF NOT EXISTS idx_ownership_signals_tickers
    ON ownership_signals USING GIN (tickers);

COMMENT ON TABLE ownership_signals IS
  'Очередь поводов посмотреть, а не фактов. В world_facts отсюда ничего не попадает '
  'автоматически: автомат предлагает, человек утверждает.';
COMMENT ON COLUMN ownership_signals.strength IS
  'строгий — формулировки 714-П, почти всегда настоящее раскрытие; '
  'широкий — доля/пакет рядом с продал/купил, включая планы и слухи.';
