-- Аннотация к посту: на каких данных он стоит и на какое число они актуальны.
--
-- ЗАЧЕМ. Числа из карточки компании я сначала отдал модели прямо в бриф с указанием
-- «максимум одно число, если объясняет повод». Это инструкция, а не гарантия: модель
-- уже показывала, что поле в брифе считает обязанным израсходовать — именно так
-- черновик разбухал до 1 105 знаков против медианы жанра 661.
--
-- Аннотация убирает причину, а не симптом. Числа перестают быть материалом для текста
-- и становятся подписью под ним: пост объясняет словами («долговая нагрузка выросла
-- втрое»), а цифры и даты стоят отдельной строкой, собранной КОДОМ.
--
-- ⚠️ ПОЧЕМУ СОБИРАЕТ КОД, А НЕ МОДЕЛЬ. Ровно этот урок уже оплачен фирменной подписью:
-- промпт требовал от модели писать её самой, она писала, и на публикации подпись
-- добавлялась ВТОРОЙ раз — 18 черновиков из 23. Вывод записан в
-- signals/publish/telegram.py: подпись принадлежит слою публикации, а не тексту
-- черновика. Аннотация — то же самое, только с числами, где цена ошибки выше:
-- выдуманное число неотличимо от настоящего.
--
-- Побочная выгода: дата попадает туда, где она нужна, без надежды на пересказ. Сейчас
-- предупреждение «[СНИМКУ 5 ЛЕТ]» вшивается внутрь факта и живёт только если модель
-- его перескажет; в аннотации дата стоит просто потому, что это её формат.
--
-- Применение на проде:
--   docker cp db/migrations/073_candidate_annotation.sql frame-db-1:/tmp/
--   docker exec frame-db-1 psql -U postgres -d moex_db -f /tmp/073_candidate_annotation.sql

ALTER TABLE content_candidates ADD COLUMN IF NOT EXISTS annotation TEXT;

COMMENT ON COLUMN content_candidates.annotation IS
  'Строка «на основании таких-то данных, актуальных на такое-то число». Собирается '
  'кодом при сборке брифа, приклеивается на слое публикации перед фирменной подписью. '
  'Модель её НЕ пишет и не редактирует: числа, придуманные моделью, неотличимы от '
  'настоящих.';
