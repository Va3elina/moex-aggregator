-- Поабзацный разбор судьи (Шаг Г) — правка Вадима 01.09.2026:
-- «хочу как-то помочь развить чуйку, чтобы много ставилось под сомнение,
--  каждый абзац и всё, что написано».
--
-- Зачем отдельная колонка, а не поле внутри judge_items. judge_items — плоский
-- словарь бинарных пунктов по ВСЕМУ посту, и именно эта плоскость подвела на
-- кандидате 1638: вердикт «годится», ноль провалов, ноль дефектов — при том что
-- человек отклонил черновик с тремя замечаниями, и каждое относилось к своему
-- абзацу. Абзац 2 держал утверждение о предвидении на отрыве в один день, абзац 3
-- повторял абзац 2 теми же словами, абзац 4 подавал догадку о мотиве толпы как
-- факт. Пункт no_redundancy повтор не поймал: когда модель оценивает пост целиком,
-- она его просматривает, а не разбирает.
--
-- Поабзацный вывод физически не даёт проскользнуть: на каждый абзац нужно назвать
-- утверждение, опору в брифе и сомнение. Отсюда и структура JSONB:
--   [{"n":1,"claim":"…","supported_by":"…","supported":true,"doubt":null}, …]
--
-- Абзацы без опоры считаются провалами ворот B (см. _derive_judge_verdict):
-- один — «спорно», два и больше — «брак».
ALTER TABLE content_candidates ADD COLUMN IF NOT EXISTS judge_paragraphs JSONB;
