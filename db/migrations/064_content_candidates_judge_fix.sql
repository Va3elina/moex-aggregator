-- Судья не только размечает, но и правит. Решение Вадима 01.09.2026: «раз судья
-- заметил ошибки, то может он их и исправит — у него есть доступ к новости,
-- значениям индикаторов».
--
-- Доступ действительно есть: судья получает ТОТ ЖЕ бриф, что писатель (новость,
-- даты, рамка, позиции, цена, связи, история рейтинга) плюс internal_token и
-- api_host. Прямого доступа к БД у него НЕТ — только наши внутренние эндпоинты.
-- Поэтому правка возможна строго в границах брифа, и это ровно то ограничение,
-- которое нужно: новых чисел он взять негде.
--
-- ⚠️ Три предохранителя, без которых правка ломает смысл проверки:
--
-- 1. ВЕРДИКТ ОСТАЁТСЯ ВЫДАННЫМ НА ИСХОДНЫЙ ТЕКСТ. Судья не перепроверяет свою же
--    правку: иначе он ставит «годится» себе, и независимость второго прохода, ради
--    которой Шаг Г и существует, исчезает. В карточке вердикт и правка показаны
--    раздельно.
-- 2. ОРИГИНАЛ ПИСАТЕЛЯ СОХРАНЯЕТСЯ (draft_text_ai не трогается, плюс запись в
--    content_feedback с обеими версиями). Дифф «писатель → судья» — это данные, на
--    которых видно, что именно судья считает правкой.
-- 3. ОДНА ПОПЫТКА. Никакого цикла «правка → перепроверка → правка»: Вадим 01.09
--    отдельно решил цикл не замыкать, и судья, правящий себя по кругу, — это он же.
--
-- ⚠️ Почему отдельная колонка, а не признак внутри judge_items: карточке нужно
-- показать человеку, что текст перед ним УЖЕ не тот, что написал писатель. Сегодня
-- было наглядно, как дорого стоит вердикт, относящийся к другому тексту (см.
-- draft_hash): путать «текст писателя» и «текст судьи» нельзя тем же образом.
ALTER TABLE content_candidates ADD COLUMN IF NOT EXISTS judge_fixed_at TIMESTAMPTZ;
ALTER TABLE content_candidates ADD COLUMN IF NOT EXISTS judge_fix_note TEXT;
