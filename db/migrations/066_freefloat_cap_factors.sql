-- Хранить сами коэффициенты, а не только их произведение.
--
-- ⚠️ Что было не так. Macro/fetch_freefloat_cap.py забирает у ISS ОБА коэффициента —
-- ff_factor (доля свободно обращающихся акций) и w_factor (ограничивающий вес,
-- у МосБиржи он называется LW) — перемножает их с cap_total и сохраняет ТОЛЬКО
-- произведение ffcap. Сами коэффициенты выбрасывались.
--
-- Из-за этого 01.09.2026 нельзя было проверить своими данными строчку мандата
-- «free-float Татнефти с 32% до 49%»: пришлось идти в ISS руками. И главное — мы не
-- видели w_factor вообще, хотя именно он определил результат прошлого мандата:
--   SBER 18.06: ff=0,48  w=0,3000  вес 13,96%
--   SBER 19.06: ff=0,48  w=0,2759  вес 13,03%
-- free-float не менялся, срезали ограничивающий коэффициент — и вес ушёл за ним.
--
-- ⚠️ w_factor из ISS и опубликованный LW — НЕ одно и то же число. У SBER ISS даёт
-- 0,2759146, а в базе расчёта на 18.09.2026 стоит LW = 0,3; у TATN ISS 0,8 и LW 0,5.
-- Похоже, ISS отдаёт LW после какой-то дополнительной нормировки. Поэтому колонка
-- называется w_factor (как в ISS), а не lw: храним то, что реально пришло, и не
-- выдаём одно за другое.
ALTER TABLE freefloat_cap ADD COLUMN IF NOT EXISTS ff_factor NUMERIC;
ALTER TABLE freefloat_cap ADD COLUMN IF NOT EXISTS w_factor  NUMERIC;

COMMENT ON COLUMN freefloat_cap.ff_factor IS
  'Коэффициент free-float МосБиржи из ISS (0..1). Точность 2 знака.';
COMMENT ON COLUMN freefloat_cap.w_factor IS
  'Ограничивающий весовой коэффициент из ISS (у МосБиржи — LW). НЕ равен '
  'опубликованному LW: ISS отдаёт его после дополнительной нормировки.';
