-- 078: бюджет считается ПОСУТОЧНО, а не помесячно.
--
-- Миграция 076 завела учёт по месяцам — это была моя ошибка в чтении лимита
-- FinanceMarker. Лимит суточный (400/день) и обнуляется каждые сутки. Разница не
-- косметическая: помесячный учёт растягивал бы один полный обход на месяц (по 4
-- компании в день) там, где все 123 компании укладываются в одни сутки, — и при
-- этом навсегда запирал бы докачку после первого же неудачного дня, потому что
-- «месячный» расход не обнулялся бы до первого числа.
--
-- period_month → period_day. Старую строку переносим как расход за 04.09.2026.

ALTER TABLE api_budget RENAME COLUMN period_month TO period_day;
COMMENT ON COLUMN api_budget.period_day IS 'сутки квоты; лимит FinanceMarker обнуляется ежедневно';

-- Строка 076 стояла на первое число месяца — переносим на день, когда расход был.
UPDATE api_budget SET period_day = DATE '2026-09-04'
 WHERE source = 'financemarker' AND period_day = DATE '2026-09-01';
