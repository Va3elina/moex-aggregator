-- Профиль стиля принятого черновика. Решение Вадима 01.09: считать профиль в Шаге В
-- автоматически, чтобы писатель видел своё отклонение ДО отправки.
--
-- ⚠️ Зачем хранить, если писатель и так проверяется на лету. Замер 01.09 показал, что
-- за день правок плотность чисел стала ВТРОЕ выше канала (1,35 против 0,40) — при
-- том что каждый отдельный запрет был верным по существу. Дрейф такого рода виден
-- только на РЯДЕ черновиков, поэтому профиль каждого принятого текста надо сохранять:
-- иначе следующий перекос снова заметит человек, а не замер.
--
-- ⚠️ Это НЕ оценка качества. В корпусе нет оценок качества, известно лишь что канал
-- это опубликовал. Колонка измеряет похожесть на канал; за факты отвечает судья.
