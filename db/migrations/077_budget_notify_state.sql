-- 077: уведомлять о СМЕНЕ состояния бюджета, а не на каждом прогоне.
--
-- Зачем. fm_cards_daily стоит в дневном расписании, и пока месячная квота выбрана,
-- он честно упирается в потолок и честно шлёт пуш — каждый день до конца месяца.
-- 27 одинаковых сообщений «бюджет исчерпан» не добавляют ни бита информации к
-- первому и работают ровно наоборот: приучают пролистывать канал не читая. Тогда
-- в нём потеряется и то сообщение, которое действительно важно.
--
-- Поэтому состояние запоминается, и пуш уходит только на переходе:
-- «работал → исчерпан» и «исчерпан → снова работает».

ALTER TABLE api_budget ADD COLUMN IF NOT EXISTS notified_state VARCHAR(16);
ALTER TABLE api_budget ADD COLUMN IF NOT EXISTS notified_at TIMESTAMPTZ;

COMMENT ON COLUMN api_budget.notified_state IS 'о каком состоянии уже сообщали: исчерпан / ок. Пуш только при смене';

-- О текущем исчерпании уже сообщено (04.09, четыре раза) — не повторять.
UPDATE api_budget SET notified_state = 'исчерпан', notified_at = now()
 WHERE source = 'financemarker' AND period_month = DATE '2026-09-01' AND spent >= limit_total;
