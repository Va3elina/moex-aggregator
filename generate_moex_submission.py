def border(color="BBBBBB"):
    s = Side(style="thin", color=color)
    return Border(left=s, right=s, top=s, bottom=s)

def fill(hex_color):
    return PatternFill("solid", fgColor=hex_color)

C_DARK   = "1F3864"   # шапка документа
C_HEADER = "2C4770"   # заголовки столбцов
C_ROW1   = "FFFFFF"
C_ROW2   = "F2F5FA"
C_ACCENT = "D6E4F0"   # выделение id-ячейки


# ─────────────────────────────────────────────────────────────
# ОСНОВНОЙ ЛИСТ
# ─────────────────────────────────────────────────────────────

def build_sheet(wb: openpyxl.Workbook):
    ws = wb.active
    ws.title = "Индикаторы"
    ws.sheet_view.showGridLines = False

    # ── Шапка ────────────────────────────────────────────────
    ws.merge_cells("A1:H1")
    c = ws["A1"]
    c.value = "ОПИСАНИЕ АНАЛИТИЧЕСКИХ ИНДИКАТОРОВ"
    c.font = Font(name="Calibri", size=14, bold=True, color="FFFFFF")
    c.fill = fill(C_DARK)
    c.alignment = Alignment(horizontal="center", vertical="center")
    ws.row_dimensions[1].height = 32

    ws.merge_cells("A2:H2")
    c = ws["A2"]
    c.value = f"Используемые данные и методология расчёта  |  {date.today().strftime('%d.%m.%Y')}"
    c.font = Font(name="Calibri", size=10, color="FFFFFF", italic=True)
    c.fill = fill("344F6E")
    c.alignment = Alignment(horizontal="center", vertical="center")
    ws.row_dimensions[2].height = 20

    ws.row_dimensions[3].height = 6  # отступ

    # ── Заголовки столбцов ───────────────────────────────────
    HEADERS = [
        "№",
        "Название индикатора",
        "Описание",
        "Используемые данные",
        "Источник\n(API MOEX)",
        "Порядок расчёта",
        "Что получается\nна выходе",
        "Обновление",
    ]
    WIDTHS = [4, 26, 36, 36, 30, 42, 28, 14]

    hdr_row = 4
    for ci, (h, w) in enumerate(zip(HEADERS, WIDTHS), start=1):
        c = ws.cell(row=hdr_row, column=ci, value=h)
        c.font = Font(name="Calibri", size=9, bold=True, color="FFFFFF")
        c.fill = fill(C_HEADER)
        c.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
        c.border = border()
        ws.column_dimensions[get_column_letter(ci)].width = w
    ws.row_dimensions[hdr_row].height = 30

    # ── Данные ───────────────────────────────────────────────
    for i, ind in enumerate(INDICATORS):
        row = hdr_row + 1 + i
        row_fill_color = C_ROW1 if i % 2 == 0 else C_ROW2
        row_fill = fill(row_fill_color)

        values = [
            ind["id"],
            ind["name"],
            ind["description"],
            ind["data_used"],
            ind["data_source"],
            ind["formula"],
            ind["output"],
            ind["update"],
        ]

        for ci, val in enumerate(values, start=1):
            c = ws.cell(row=row, column=ci, value=val)
            c.fill = row_fill
            c.border = border()
            c.alignment = Alignment(
                horizontal="center" if ci == 1 else "left",
                vertical="top",
                wrap_text=True,
            )
            if ci == 1:
                c.font = Font(name="Calibri", size=11, bold=True, color=C_DARK)
                c.fill = fill(C_ACCENT)
            elif ci == 2:
                c.font = Font(name="Calibri", size=9, bold=True)
            elif ci == 6:
                c.font = Font(name="Consolas", size=8.5)
            else:
                c.font = Font(name="Calibri", size=9)

        ws.row_dimensions[row].height = 175

    ws.freeze_panes = ws.cell(row=hdr_row + 1, column=1)


# ─────────────────────────────────────────────────────────────

def main():
    wb = openpyxl.Workbook()
    build_sheet(wb)
    out = r"C:\Users\Vadim\PycharmProjects\MOEX\MOEX_Indicators_For_Submission_v2.xlsx"
    wb.save(out)


if __name__ == "__main__":
    main()
